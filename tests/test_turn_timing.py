PARTS = ("runtime_ms", "ttft_ms", "generate_ms", "tail_ms")


class Ticks:
    """A monotonic fake: each read returns the time set by the test (seconds)."""

    def __init__(self) -> None:
        self.t = 100.0

    def __call__(self) -> float:
        return self.t

    def at(self, t: float) -> None:
        self.t = 100.0 + t


def adds_up(timing: dict[str, Any]) -> None:
    assert sum(int(timing.get(k, 0)) for k in PARTS) == timing["total_ms"]
    assert all(int(timing.get(k, 0)) >= 0 for k in PARTS)


