class ClockedRuntime:
    """The planner's runtime on the daemon's FakeClock: its start takes 0.3 s, its first output comes 2 s after, its
    answer is done 0.5 s later; it reports no timing of its own, so FERB's arrival clock times the call."""
    name = "fake"
    limits = ModelLimits("fake-model", 1_000_000, 100_000, "test double")

    def __init__(self, clock: Any, answer: str) -> None:
        self.clock, self.answer = clock, answer

    async def start(self, task: Task, request: ModelRequest, run_token: str) -> RunHandle:
        self.clock.advance(0.3)
        return RunHandle("run-clocked", self.name, task.id, {"start_steps": {"spawn": 300}})

    async def events(self, run: RunHandle) -> AsyncIterator[RuntimeEvent]:
        self.clock.advance(2.0)
        yield RuntimeEvent("text_delta", {"text": self.answer[:5]})
        self.clock.advance(0.5)
        yield RuntimeEvent("text_delta", {"text": self.answer[5:]})
        self.clock.advance(0.01)
        yield RuntimeEvent("usage", {"input_tokens": 10, "output_tokens": 5})
        yield RuntimeEvent("final", {"text": self.answer})

    async def cancel(self, run: RunHandle) -> None:
        return None


def spans_of(d: RunningDaemon, request_id: str) -> list[dict[str, Any]]:
    async def read() -> list[dict[str, Any]]:
        return d.daemon.spans.tree_json(request_id)          # type: ignore[union-attr]
    return d.run(read())                                     # type: ignore[no-any-return]


def journal(d: RunningDaemon, kind: str) -> list[Any]:
    async def read() -> list[Any]:
        return d.daemon.journal.of_kind(kind)                # type: ignore[union-attr]
    return d.run(read())                                     # type: ignore[no-any-return]


