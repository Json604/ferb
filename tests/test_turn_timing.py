def test_a_call_whose_usage_report_follows_its_tool_ends_before_the_tool_and_the_next_begins_after_it() -> None:
    """Codex reports a call's usage after its tool already ran (the owner's trace: a 5 ms lookup at 42.615, usage at
    42.639): the tool's time belongs to neither call, and the next call's request is its own."""
    now = Ticks()
    timer = CallTimer(now)
    timer.begin()                      # turn/start sent at 0
    now.at(0.4)
    timer.sent()                       # the request went out at 0.4
    now.at(4.4)
    timer.output()                     # first output at 4.4
    now.at(4.6)
    timer.output()                     # the tool call generated by 4.6
    now.at(4.605)
    timer.handed_back()                # the tool's result went back at 4.605
    now.at(4.61)
    timer.sent()                       # the next request at 4.61, before the first call's usage arrived
    now.at(4.625)
    first = timer.done()               # usage of call 1 at 4.625
    assert first == {"by": "runtime", "runtime_ms": 400, "ttft_ms": 4000, "generate_ms": 200, "tail_ms": 25,
                     "total_ms": 4625}
    now.at(9.0)
    timer.output()
    now.at(9.7)
    timer.output()
    now.at(9.72)
    second = timer.done()
    assert second == {"by": "runtime", "runtime_ms": 5, "ttft_ms": 4390, "generate_ms": 700, "tail_ms": 20,
                      "total_ms": 5115}
    adds_up(first)
    adds_up(second)


def test_steps_add_up_to_their_total_and_a_call_without_output_is_all_waiting() -> None:
    now = Ticks()
    steps = Steps(now)
    for t, name in ((0.0004, "a"), (0.0011, "b"), (0.0016, "a")):
        now.at(t)
        steps.mark(name)
    assert steps.steps == {"a": 1, "b": 1} and sum(steps.steps.values()) == steps.total_ms == 2
    timer = CallTimer(now, "arrival")
    now.at(3)
    late = timer.done()
    assert late["by"] == "arrival" and "runtime_ms" not in late and late["ttft_ms"] == late["total_ms"]


