def test_a_chat_turns_trace_says_where_its_time_went_and_the_parts_add_up(daemon: RunningDaemon) -> None:
    clock = daemon.daemon.clock
    script = install(daemon, [])
    answer = json.dumps({"kind": "reply", "text": "Hello!", "task": None})
    planner = ClockedRuntime(clock, answer)

    def make(role: str, *, mode: str, tool_names: list[str], schema: dict[str, Any], effort: str | None = None) -> Any:
        assert role == "orchestrator" and schema is SUPERVISOR_SCHEMA
        return planner

    daemon.daemon.supervisor.make_runtime = make           # type: ignore[union-attr]

    taken_in = asyncio.Event()             # the intake read the environment: its next wait is the front window's
    supervisor = daemon.daemon.supervisor
    environment = supervisor.environment                    # type: ignore[union-attr]

    async def environment_read(words: str) -> Any:
        read = environment(words)
        facts = await read if inspect.isawaitable(read) else read
        taken_in.set()
        return facts
    supervisor.environment = environment_read               # type: ignore[union-attr]

    async def capture(request_id: str, client_pid: int | None = None) -> Any:
        await taken_in.wait()
        clock.advance(0.5)                                  # the planner waited 0.5 s for it (DMN-520's wait)
        return None
    daemon.daemon.front_window = capture
    events = chat(daemon, "Hello ferb, do you know me?")
    assert [e["text"] for e in events if e["type"] == "reply"] == ["Hello!"] and not script.requests
    request_id = journal(daemon, "chat.message")[-1].data["request_id"]
    nodes = spans_of(daemon, request_id)
    flat = [n for root in nodes for n in trace_timing.walk([root])]
    [prepare] = [n for n in flat if n["kind"] == "planner.prepare"]
    [turn] = [n for n in flat if n["kind"] == "model.turn"]
    [usage] = [n for n in flat if n["kind"] == "model.usage"]
    [reply] = [n for n in flat if n["kind"] == "planner.reply"]

    before = prepare["output"]                               # FERB before the model call, step by step
    assert before["steps_ms"]["front_window"] == 500
    assert sum(before["steps_ms"].values()) == before["total_ms"] and prepare["ended_at"] <= turn["started_at"]

    timed = turn["output"]["timing"]                          # the turn around its model call
    call = timed["call"]
    assert call["steps_ms"]["start"] == 300 and call["start_steps_ms"] == {"spawn": 300}
    assert call["steps_ms"]["stream"] == 2510 and call["model_calls"] == 1
    assert sum(call["steps_ms"].values()) == call["total_ms"] == timed["steps_ms"]["model_call"]
    assert sum(timed["steps_ms"].values()) == timed["total_ms"]

    each = usage["output"]["timing"]                         # the model call, split
    assert each == {"by": "arrival", "ttft_ms": 2000, "generate_ms": 500, "tail_ms": 10, "total_ms": 2510}
    assert isinstance(reply["output"]["after_decision_ms"], int)

    [entry] = trace_timing.breakdown(nodes)                   # what `ferb trace --json` adds
    assert entry["kind"] == "planner" and entry["ferb_before"]["steps_ms"]["front_window"] == 500
    assert entry["runtime_start"] == {"ms": 300, "steps_ms": {"spawn": 300}}
    assert [c["total_ms"] for c in entry["model_calls"]] == [2510]
    assert trace_timing.lines([entry])                        # and `--full` prints it


