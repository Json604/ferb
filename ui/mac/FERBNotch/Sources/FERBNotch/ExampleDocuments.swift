import AppKit

/// A real, local artifact for the interface preview. Source contents are never read.
@MainActor
final class ExampleDocuments {
    private let directory: URL

    init(directory: URL? = nil) {
        self.directory = directory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("FERB Notch/Examples", isDirectory: true)
    }

    func create(id: UUID, request: String, sources: [URL]) throws -> URL {
        let folder = directory.appendingPathComponent(id.uuidString, isDirectory: true)
        let url = folder.appendingPathComponent("Example brief.pdf")
        if FileManager.default.fileExists(atPath: url.path) { return url }
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let data = NSMutableData()
        var page = CGRect(x: 0, y: 0, width: 612, height: 792)
        guard let consumer = CGDataConsumer(data: data),
              let context = CGContext(consumer: consumer, mediaBox: &page, nil) else {
            throw CocoaError(.fileWriteUnknown)
        }
        context.beginPDFPage(nil)
        context.translateBy(x: 0, y: page.height)
        context.scaleBy(x: 1, y: -1)
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(cgContext: context, flipped: true)
        NSColor.white.setFill()
        NSBezierPath(rect: page).fill()
        draw("FERB", at: 48, height: 20, size: 11, weight: .semibold, secondary: true)
        draw("Example brief", at: 82, height: 48, size: 30, weight: .semibold)
        draw("Your request", at: 157, height: 24, size: 13, weight: .semibold)
        draw(String(request.prefix(900)), at: 187, height: 155, size: 14)
        draw("Attached context", at: 365, height: 24, size: 13, weight: .semibold)
        let names = sources.prefix(6).map(\.lastPathComponent)
        var contextText = names.isEmpty ? "No files attached." : names.joined(separator: "\n")
        if sources.count > 6 { contextText += "\nAnd \(sources.count - 6) more files." }
        draw(contextText, at: 395, height: 150, size: 13)
        draw("Ready to open, preview, or share.", at: 588, height: 30, size: 17, weight: .medium)
        draw("Interface example. This PDF demonstrates a finished handoff; it was not generated by FERB. Only file names are included. Source contents were not read or sent.",
             at: 654, height: 70, size: 11, secondary: true)
        NSGraphicsContext.restoreGraphicsState()
        context.endPDFPage()
        context.closePDF()
        try (data as Data).write(to: url, options: .atomic)
        return url
    }

    private func draw(_ text: String, at y: CGFloat, height: CGFloat, size: CGFloat,
                      weight: NSFont.Weight = .regular, secondary: Bool = false) {
        let paragraph = NSMutableParagraphStyle()
        paragraph.lineSpacing = 4
        paragraph.lineBreakMode = .byTruncatingTail
        (text as NSString).draw(in: CGRect(x: 52, y: y, width: 508, height: height), withAttributes: [
            .font: NSFont.systemFont(ofSize: size, weight: weight),
            .foregroundColor: NSColor(white: secondary ? 0.4 : 0.12, alpha: 1),
            .paragraphStyle: paragraph
        ])
    }
}
