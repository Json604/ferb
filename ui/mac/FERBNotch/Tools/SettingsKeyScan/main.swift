import Foundation

// APP-728 with TEST-508: run by SettingsKeysPlugin when the test target builds. It reads FERB.app's Swift sources
// (the build, never a test, reads the repository) and writes every UserDefaults key they write or read (literal keys
// in calls, @AppStorage, key constants) into a Swift file the tests compile in, so the test that fails on an undeclared
// preference reads only its own module. Arguments: the output file, then the source files.
let arguments = Array(CommandLine.arguments.dropFirst())
guard let output = arguments.first else {
    FileHandle.standardError.write(Data("usage: SettingsKeyScan OUTPUT SOURCE...\n".utf8))
    exit(2)
}
let patterns = [
    #"\.(set|object|bool|string|double|integer|float|data|array|dictionary|removeObject|url|stringArray)\((?:[^()]|\([^()]*\))*?forKey:\s*"([^"]+)""#,
    #"AppStorage\("([^"]+)""#,
    #"static let \w*[Kk]ey\w*\s*=\s*"([^"]+)""#,
]
let expressions = try patterns.map { try NSRegularExpression(pattern: $0) }
var found: [String: String] = [:]
for path in arguments.dropFirst() where path.hasSuffix(".swift") {
    let text = try String(contentsOfFile: path, encoding: .utf8)
    let range = NSRange(text.startIndex..., in: text)
    for expression in expressions {
        for match in expression.matches(in: text, range: range) {
            guard let key = Range(match.range(at: match.numberOfRanges - 1), in: text) else { continue }
            found[String(text[key])] = URL(fileURLWithPath: path).lastPathComponent
        }
    }
}
func literal(_ text: String) -> String {
    "\"" + text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
}
let rows = found.keys.sorted().map { "        \(literal($0)): \(literal(found[$0]!))," }

// APP-796: every line of FERB.app's sources that puts a window or a menu on screen (a window class, an alert, a file
// picker, Quick Look, Sparkle's window, the status item, a menu, a picker, a popover, a sheet), and every line that makes
// FERB the active app or runs a modal window, as "File.swift: code". The Space rule's test fails on one its table of
// paths doesn't list. The debug-only playground isn't in FERB.app and isn't listed.
let presenterPatterns = [
    #"class \w+: (NSWindow|NSPanel)\b"#, #"(NSWindow|NSPanel|FERBAppWindow)\(contentRect"#, #"NSAlert\(\)"#,
    #"NSOpenPanel\(\)"#, #"NSSavePanel\(\)"#, #"QLPreviewPanel\.shared\(\)"#, #"checkForUpdates\(nil\)"#,
    #"statusItem\(withLength"#, #"\.popUp\(positioning"#, #"func menu\(for event"#, #"\.contextMenu"#,
    #"\bPicker\("#, #"\bMenu\("#, #"\.popover\("#, #"\.alert\("#, #"\.sheet\("#,
]
let activationPatterns = [#"\.activate\("#, #"\.runModal\(\)"#]
func lines(matching patterns: [String], skipping skipped: Set<String> = []) throws -> [String] {
    let expressions = try patterns.map { try NSRegularExpression(pattern: $0) }
    var rows: [String] = []
    for path in arguments.dropFirst() where path.hasSuffix(".swift") && !path.contains("/Playground/") {
        let name = URL(fileURLWithPath: path).lastPathComponent
        guard !skipped.contains(name) else { continue }
        for line in try String(contentsOfFile: path, encoding: .utf8).components(separatedBy: "\n") {
            let code = line.trimmingCharacters(in: .whitespaces)
            guard !code.hasPrefix("//") else { continue }
            let range = NSRange(code.startIndex..., in: code)
            if expressions.contains(where: { $0.firstMatch(in: code, range: range) != nil }) { rows.append(name + ": " + code) }
        }
    }
    return rows.sorted()
}
let presenterRows = try lines(matching: presenterPatterns, skipping: ["AppWindowPresentation.swift"]).map { "        \(literal($0))," }
let activationRows = try lines(matching: activationPatterns).map { "        \(literal($0))," }
let file = """
    // Generated by SettingsKeyScan (Tools/SettingsKeyScan) when the tests build; never edited or checked in.
    /// Every UserDefaults key FERB.app's sources write or read, with the file it was found in (APP-728).
    enum SourceSettingsKeys {
        static let found: [String: String] = [
    \(rows.isEmpty ? "    :" : rows.joined(separator: "\n"))
        ]
    }

    /// Every source line that puts a window or a menu on screen, as "File.swift: code" (APP-796).
    enum SourcePresenters {
        static let lines: [String] = [
    \(presenterRows.joined(separator: "\n"))
        ]
        /// Every source line that makes FERB the active app or runs a modal window.
        static let activations: [String] = [
    \(activationRows.joined(separator: "\n"))
        ]
    }

    """
let url = URL(fileURLWithPath: output)
if (try? String(contentsOf: url, encoding: .utf8)) != file {
    try file.write(to: url, atomically: true, encoding: .utf8)
}
