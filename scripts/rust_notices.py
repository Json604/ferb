"""THIRD_PARTY_NOTICES.md's section for the Rust crates FERB.app's Rust build ships (scripts/build-app-rust.sh).

    python3 -I scripts/rust_notices.py --write    rewrite the section from Cargo.lock (cargo metadata, offline)
    python3 -I scripts/rust_notices.py --check    exit 1 when the section isn't what --write would write

The shipped crates are those `ferbd`, `ferb` and `ferb-native-host` (workspace members, locked by rust/Cargo.lock)
depend on as normal dependencies on either Mac architecture: build-time and test-only crates
don't ship. For each: its version, its licence expression, the licence FERB takes it under (MIT, then Apache-2.0,
from an OR choice; every part of an AND) and the copyright lines of its licence files. MIT's and Apache-2.0's texts
follow once; any other licence's text is quoted from the crates' own files. The rest of THIRD_PARTY_NOTICES.md is
never touched. A build tool: nothing here ships or runs in FERB."""

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = ROOT / "THIRD_PARTY_NOTICES.md"
START = "<!-- rust-crates: generated by scripts/rust_notices.py from the Cargo.lock files; do not edit by hand -->"
END = "<!-- /rust-crates -->"
TARGETS = ("aarch64-apple-darwin", "x86_64-apple-darwin")
# (manifest, the packages of it that ship)
SHIPPED = ((ROOT / "rust" / "crates" / "ferbd" / "Cargo.toml", ("ferbd",)),
           (ROOT / "rust" / "Cargo.toml", ("ferb-native-host",)))
PREFERRED = ("MIT", "Apache-2.0")
LICENCE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|UNLICENSE|NOTICE)", re.I)
COPYRIGHT = re.compile(r"^\s*(copyright\s*(\(c\)|©|\d)|\(c\)\s*\d|©)", re.I)
# The file of a crate that holds one licence's text, by a hint in its name (else the files naming neither MIT nor Apache)
HINTS = {"Unicode-3.0": "UNICODE", "Zlib": "ZLIB", "BSD-3-Clause": "BSD", "ISC": "ISC", "CDLA-Permissive-2.0": "CDLA"}
TEMPLATE = re.compile(r"\[yyyy\]|<year>|\[year\]|\{yyyy\}|<copyright holders>|\[name of copyright owner\]", re.I)
EMAIL = re.compile(r"\s*<[^<>@\s]+@[^<>\s]+>")

MIT = """Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated
documentation files (the "Software"), to deal in the Software without restriction, including without limitation the
rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to permit
persons to whom the Software is furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all copies or substantial portions of the
Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE
WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR
COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR
OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE."""


def metadata(manifest: Path, target: str) -> dict:
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked", "--offline",
                          "--filter-platform", target, "--manifest-path", str(manifest)],
                         capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def shipped_packages() -> dict[tuple[str, str], dict]:
    """(name, version) -> cargo's package record, for every registry crate a shipped program depends on."""
    found: dict[tuple[str, str], dict] = {}
    for manifest, roots in SHIPPED:
        for target in TARGETS:
            meta = metadata(manifest, target)
            packages = {p["id"]: p for p in meta["packages"]}
            nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
            todo = [i for i, p in packages.items() if p["name"] in roots and p["source"] is None]
            seen: set[str] = set()
            while todo:
                pid = todo.pop()
                if pid in seen:
                    continue
                seen.add(pid)
                for dep in nodes[pid]["deps"]:
                    if any(k["kind"] is None for k in dep["dep_kinds"]):
                        todo.append(dep["pkg"])
            for pid in seen:
                p = packages[pid]
                if p["source"] is not None:
                    found[(p["name"], p["version"])] = p
    return found


def chosen(expression: str) -> list[str]:
    """The licences FERB takes a crate under: each AND part, and in an OR the first of PREFERRED it offers."""
    expr = (expression or "").replace("/", " OR ")
    parts = [p.strip().strip("()").strip() for p in re.split(r"\bAND\b", expr)]
    out = []
    for part in parts:
        options = [o.strip().strip("()").strip() for o in re.split(r"\bOR\b", part)]
        pick = next((o for o in PREFERRED if o in options), options[0] if options else "")
        if pick and pick not in out:
            out.append(pick)
    return out


def licence_files(p: dict) -> list[Path]:
    folder = Path(p["manifest_path"]).parent
    return sorted(f for f in folder.iterdir() if f.is_file() and LICENCE_FILE.match(f.name))


def text_files(p: dict, lic: str) -> list[Path]:
    files = licence_files(p)
    hint = HINTS.get(lic)
    named = [f for f in files if hint and hint in f.name.upper()]
    if named:
        return named
    other = [f for f in files if "MIT" not in f.name.upper() and "APACHE" not in f.name.upper()]
    return other or files


def copyrights(p: dict) -> list[str]:
    lines: list[str] = []
    for f in licence_files(p):
        for line in f.read_text(errors="replace").splitlines():
            line = EMAIL.sub("", line).strip()
            if COPYRIGHT.match(line) and not TEMPLATE.search(line) and line not in lines and len(line) < 200:
                lines.append(line)
    if not lines:
        authors = ", ".join(EMAIL.sub("", a).strip() for a in p.get("authors") or [])
        lines.append(f"Copyright the {p['name']} authors" + (f" ({authors})" if authors else ""))
    return lines


def apache_text(packages: list[dict]) -> str:
    for p in packages:
        for f in licence_files(p):
            text = f.read_text(errors="replace")
            if "Apache License" in text and "Version 2.0, January 2004" in text and "END OF TERMS" in text:
                return text.split("END OF TERMS AND CONDITIONS")[0].strip() + "\n\nEND OF TERMS AND CONDITIONS"
    raise SystemExit("no Apache-2.0 licence text among the shipped crates' files")


def section() -> str:
    found = shipped_packages()
    packages = [found[k] for k in sorted(found)]
    out = [START, "", "## Rust crates in FERB's Rust build (ferbd, ferb, ferb-native-host)", "",
           "FERB.app's Rust build compiles these crates into its programs. Each line: the crate and version, its "
           "licence expression, and the licence FERB takes it under; then its copyright lines. MIT's and Apache-2.0's "
           "texts follow once; the other licences' texts are quoted from the crates' own files. `libsqlite3-sys` "
           "compiles in SQLite, which is in the public domain.", ""]
    others: dict[str, dict[str, list[str]]] = {}
    for p in packages:
        taken = chosen(p.get("license") or "")
        out.append(f"- **{p['name']} {p['version']}**: {p.get('license') or 'no licence field'}; "
                   f"used under {' AND '.join(taken) or 'its licence files'}")
        for line in copyrights(p):
            out.append(f"  - {line}")
        for lic in taken:
            if lic in PREFERRED:
                continue
            for f in text_files(p, lic):
                text = f.read_text(errors="replace").strip()
                others.setdefault(lic, {}).setdefault(text, []).append(f"{p['name']} {p['version']}")
    out += ["", "### MIT", "", "```", MIT, "```", "", "### Apache-2.0", "", "```", apache_text(packages), "```"]
    for lic in sorted(others):
        for text, crates in others[lic].items():
            out += ["", f"### {lic} ({', '.join(crates)})", "", "```", text, "```"]
    out += ["", END]
    return "\n".join(out) + "\n"


def current(text: str) -> tuple[str, str, str]:
    if START in text and END in text:
        before, rest = text.split(START, 1)
        inside, after = rest.split(END, 1)
        return before, START + inside + END + "\n", after.lstrip("\n")
    return text.rstrip("\n") + "\n\n", "", ""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    os.chdir(ROOT)
    text = NOTICES.read_text()
    before, old, after = current(text)
    new = section()
    if args.write:
        NOTICES.write_text(before + new + after)
        return 0
    if old != new:
        print("THIRD_PARTY_NOTICES.md's Rust crates are out of date: python3 -I scripts/rust_notices.py --write",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
