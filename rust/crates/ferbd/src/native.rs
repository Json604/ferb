//! fs.look's decoders on the Mac (`ferb/act/fs/look.py` `picture` and `pdf_page`): ImageIO for a picture, PDFKit and
//! CoreGraphics for a PDF page, drawn onto an opaque white sRGB bitmap and encoded with the screenshot's JPEG helper
//! (ferb-mac-hands' `native::paint::jpeg`). Nothing is written to disk and nothing opens on screen.

use std::ffi::c_void;
use std::ptr::NonNull;

use ferb_core::types::Dict;
use ferb_fs::look::{pair, LookError, Renderer};
use objc2::msg_send;
use objc2::rc::{Allocated, Retained};
use objc2::runtime::{AnyClass, AnyObject};
use objc2_core_foundation::{
    CFBoolean, CFData, CFDictionary, CFNumber, CFRetained, CFString, CFType, CGPoint, CGRect,
    CGSize,
};
use objc2_core_graphics::{
    CGBitmapContextCreateImage, CGColorSpace, CGContext, CGImage, CGImageAlphaInfo,
    CGInterpolationQuality, CGPDFBox, CGPDFPage,
};
use objc2_foundation::{NSData, NSString};
use objc2_image_io::CGImageSource;
use serde_json::json;

#[link(name = "PDFKit", kind = "framework")]
extern "C" {}

extern "C" {
    // CoreGraphics' CGBitmapContextCreate (not generated by objc2-core-graphics 0.3.2).
    fn CGBitmapContextCreate(
        data: *mut c_void,
        width: usize,
        height: usize,
        bits_per_component: usize,
        bytes_per_row: usize,
        space: *const CGColorSpace,
        bitmap_info: u32,
    ) -> *mut CGContext;
}

fn undecodable(why: &str) -> LookError {
    LookError::Undecodable(why.into())
}

fn rect(x: f64, y: f64, w: f64, h: f64) -> CGRect {
    CGRect {
        origin: CGPoint { x, y },
        size: CGSize {
            width: w,
            height: h,
        },
    }
}

/// `_bitmap`: an opaque white sRGB bitmap of this size, to draw a picture or a page on.
fn bitmap(width: usize, height: usize) -> Result<CFRetained<CGContext>, LookError> {
    // SAFETY: the exported color space name.
    let name: &CFString = unsafe { objc2_core_graphics::kCGColorSpaceSRGB };
    let space = CGColorSpace::with_name(Some(name))
        .ok_or_else(|| undecodable("couldn't make a picture of that size"))?;
    // SAFETY: CoreGraphics allocates the buffer (data NULL, bytes per row 0); 8 bits per component, RGBX.
    let ctx = unsafe {
        CGBitmapContextCreate(
            std::ptr::null_mut(),
            width,
            height,
            8,
            0,
            CFRetained::as_ptr(&space).as_ptr(),
            CGImageAlphaInfo::NoneSkipLast.0,
        )
    };
    let ctx =
        NonNull::new(ctx).ok_or_else(|| undecodable("couldn't make a picture of that size"))?;
    // SAFETY: the Create rule: we own the context.
    let ctx = unsafe { CFRetained::from_raw(ctx) };
    CGContext::set_rgb_fill_color(Some(&ctx), 1.0, 1.0, 1.0, 1.0);
    CGContext::fill_rect(Some(&ctx), rect(0.0, 0.0, width as f64, height as f64));
    CGContext::set_interpolation_quality(Some(&ctx), CGInterpolationQuality::High);
    Ok(ctx)
}

fn encoded(ctx: &CGContext) -> Result<Vec<u8>, LookError> {
    let image: CFRetained<CGImage> = CGBitmapContextCreateImage(Some(ctx))
        .ok_or_else(|| undecodable("couldn't make a picture of that size"))?;
    ferb_mac_hands::native::paint::jpeg(&image).map_err(|e| undecodable(&e.to_string()))
}

fn number(d: &CFDictionary, key: &CFString) -> i64 {
    // SAFETY: a CFDictionary of CFString keys; the value is checked to be a CFNumber before it is read.
    let v = unsafe { d.value(key as *const CFString as *const c_void) };
    if v.is_null() {
        return 0;
    }
    // SAFETY: a value the dictionary holds (not retained by us: borrowed for this call).
    let t: &CFType = unsafe { &*(v as *const CFType) };
    t.downcast_ref::<CFNumber>()
        .and_then(|n| n.as_i64())
        .unwrap_or(0)
}

/// `picture`: the first image, turned as its orientation says, scaled down to `max_edge` on its long side (never
/// up), as JPEG, with its format and size as the file holds it.
pub fn picture(data: &[u8], max_edge: u32) -> Result<(Vec<u8>, Dict), LookError> {
    objc2::rc::autoreleasepool(|_| {
        let bytes = CFData::from_bytes(data);
        // SAFETY: no options dictionary.
        let source = unsafe { CGImageSource::with_data(&bytes, None) }
            .ok_or_else(|| undecodable("not a picture"))?;
        // SAFETY: a source just made.
        let kind = unsafe { source.r#type() };
        // SAFETY: as above.
        let frames = unsafe { source.count() };
        let Some(kind) = kind.filter(|_| frames >= 1) else {
            return Err(undecodable("not a picture"));
        };
        // SAFETY: index 0 exists (count >= 1); no options.
        let props = unsafe { source.properties_at_index(0, None) };
        let (width, height) = match &props {
            Some(p) => {
                // SAFETY: the exported property keys.
                let (wk, hk) = unsafe {
                    (
                        objc2_image_io::kCGImagePropertyPixelWidth,
                        objc2_image_io::kCGImagePropertyPixelHeight,
                    )
                };
                (number(p, wk), number(p, hk))
            }
            None => (0, 0),
        };
        if width < 1 || height < 1 {
            return Err(undecodable("not a picture"));
        }
        // SAFETY: the exported option keys, with CFBoolean and CFNumber values.
        let (always, transform, size_key) = unsafe {
            (
                objc2_image_io::kCGImageSourceCreateThumbnailFromImageAlways,
                objc2_image_io::kCGImageSourceCreateThumbnailWithTransform,
                objc2_image_io::kCGImageSourceThumbnailMaxPixelSize,
            )
        };
        let yes = CFBoolean::new(true);
        let edge = CFNumber::new_i64(i64::from(max_edge).min(width.max(height)));
        let opts = CFDictionary::<CFString, CFType>::from_slices(
            &[always, transform, size_key],
            &[yes.as_ref(), yes.as_ref(), edge.as_ref()],
        );
        // SAFETY: index 0 exists; a dictionary of documented thumbnail options.
        let image = unsafe { source.thumbnail_at_index(0, Some(opts.as_opaque())) }
            .ok_or_else(|| undecodable("not a picture"))?;
        let (w, h) = (CGImage::width(Some(&image)), CGImage::height(Some(&image)));
        let ctx = bitmap(w, h)?;
        CGContext::draw_image(Some(&ctx), rect(0.0, 0.0, w as f64, h as f64), Some(&image));
        let mut facts = Dict::new();
        facts.insert("format".into(), json!(kind.to_string()));
        facts.insert("pixels".into(), pair(width, height));
        facts.insert("width".into(), json!(w));
        facts.insert("height".into(), json!(h));
        if frames > 1 {
            facts.insert("frames".into(), json!(frames));
            facts.insert("shown".into(), json!("the first frame"));
        }
        Ok((encoded(&ctx)?, facts))
    })
}

/// Python's `round` (half to even) for the page's pixel size.
fn round_half_even(x: f64) -> i64 {
    x.round_ties_even() as i64
}

/// `pdf_page`: one page (1-based), turned as the page says, rendered with its long side `max_edge`, as JPEG, with how
/// many pages the PDF has and the page's text layer (empty for a scan).
pub fn pdf_page(data: &[u8], number: i64, max_edge: u32) -> Result<(Vec<u8>, Dict), LookError> {
    objc2::rc::autoreleasepool(|_| {
        let cls =
            AnyClass::get(c"PDFDocument").ok_or_else(|| undecodable("not a PDF FERB can read"))?;
        let bytes = NSData::with_bytes(data);
        // SAFETY: PDFDocument's documented initializer, given an NSData; it returns nil for bytes it can't read.
        let doc: Option<Retained<AnyObject>> = unsafe {
            let a: Allocated<AnyObject> = msg_send![cls, alloc];
            msg_send![a, initWithData: &*bytes]
        };
        let doc = doc.ok_or_else(|| undecodable("not a PDF FERB can read"))?;
        // SAFETY: PDFDocument's isLocked (BOOL) and pageCount (NSUInteger).
        let locked: bool = unsafe { msg_send![&*doc, isLocked] };
        if locked {
            return Err(undecodable("the PDF is locked with a password"));
        }
        // SAFETY: as above.
        let pages: usize = unsafe { msg_send![&*doc, pageCount] };
        if number < 1 || number as usize > pages {
            return Err(LookError::NoPage(pages as i64));
        }
        // SAFETY: an index inside pageCount; the page may be nil.
        let page: Option<Retained<AnyObject>> =
            unsafe { msg_send![&*doc, pageAtIndex: (number - 1) as usize] };
        let page = page.ok_or_else(|| undecodable("not a PDF FERB can read"))?;
        // SAFETY: PDFPage's pageRef: a CGPDFPageRef the page owns (alive while `page` is).
        let page_ref: *const CGPDFPage = unsafe { msg_send![&*page, pageRef] };
        if page_ref.is_null() {
            return Err(undecodable("not a PDF FERB can read"));
        }
        // SAFETY: non-null and owned by `page`, which outlives this borrow.
        let r: &CGPDFPage = unsafe { &*page_ref };
        let b = CGPDFPage::box_rect(Some(r), CGPDFBox::CropBox);
        let (mut pw, mut ph) = (b.size.width, b.size.height);
        if CGPDFPage::rotation_angle(Some(r)) % 180 != 0 {
            std::mem::swap(&mut pw, &mut ph);
        }
        if pw <= 0.0 || ph <= 0.0 {
            return Err(undecodable("the page has no size"));
        }
        let k = f64::from(max_edge) / pw.max(ph);
        let (w, h) = (
            round_half_even(pw * k).max(1),
            round_half_even(ph * k).max(1),
        );
        let ctx = bitmap(w as usize, h as usize)?;
        CGContext::scale_ctm(Some(&ctx), k, k);
        CGContext::concat_ctm(
            Some(&ctx),
            CGPDFPage::drawing_transform(
                Some(r),
                CGPDFBox::CropBox,
                rect(0.0, 0.0, pw, ph),
                0,
                true,
            ),
        );
        CGContext::draw_pdf_page(Some(&ctx), Some(r));
        let jpeg = encoded(&ctx)?;
        // SAFETY: PDFPage's string (NSString, may be nil).
        let text: Option<Retained<NSString>> = unsafe { msg_send![&*page, string] };
        let text = text.map(|t| t.to_string()).unwrap_or_default();
        let mut facts = Dict::new();
        facts.insert("format".into(), json!("com.adobe.pdf"));
        facts.insert("page".into(), json!(number));
        facts.insert("pages".into(), json!(pages));
        facts.insert("width".into(), json!(w));
        facts.insert("height".into(), json!(h));
        facts.insert("text".into(), json!(text.trim()));
        Ok((jpeg, facts))
    })
}

/// fs.look's renderer on the Mac.
pub struct MacRenderer;

impl Renderer for MacRenderer {
    fn picture(&self, data: &[u8], max_edge: u32) -> Result<(Vec<u8>, Dict), LookError> {
        picture(data, max_edge)
    }
    fn pdf_page(
        &self,
        data: &[u8],
        number: i64,
        max_edge: u32,
    ) -> Result<(Vec<u8>, Dict), LookError> {
        pdf_page(data, number, max_edge)
    }
}

/// The pasteboard's change count only (never its contents): NSPasteboard.generalPasteboard.changeCount.
pub fn pasteboard_change_count() -> i64 {
    objc2::rc::autoreleasepool(|_| {
        objc2_app_kit::NSPasteboard::generalPasteboard().changeCount() as i64
    })
}
