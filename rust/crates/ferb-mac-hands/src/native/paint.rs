//! Images in memory with CoreGraphics and ImageIO (evidence/mask.py, screenshot.py `_jpeg`, recording.py's review
//! sheet): decode, paint boxes opaque black, encode JPEG at 0.8. Nothing is written to disk here.

use std::ffi::c_void;
use std::ptr::NonNull;

use objc2_core_foundation::{
    CFData, CFDictionary, CFMutableData, CFNumber, CFRetained, CFString, CFType, CGPoint, CGRect,
    CGSize,
};
use objc2_core_graphics::{
    CGBitmapContextCreateImage, CGColorSpace, CGContext, CGImage, CGImageAlphaInfo,
};
use objc2_image_io::{
    kCGImageDestinationLossyCompressionQuality, CGImageDestination, CGImageSource,
};

use crate::error::{HandError, Result};
use crate::mask::ImgBox;
use crate::ocr::Paint;
use crate::shots::JPEG_QUALITY;

extern "C" {
    // CoreGraphics' CGBitmapContextCreate (not generated by objc2-core-graphics 0.3.2).
    fn CGBitmapContextCreate(
        data: *mut c_void,
        width: usize,
        height: usize,
        bits_per_component: usize,
        bytes_per_row: usize,
        space: *const CGColorSpace,
        bitmap_info: u32,
    ) -> *mut CGContext;
}

fn rect(x: f64, y: f64, w: f64, h: f64) -> CGRect {
    CGRect {
        origin: CGPoint { x, y },
        size: CGSize {
            width: w,
            height: h,
        },
    }
}

/// The first image of encoded bytes; ValueError in Python when it can't be decoded.
pub fn decode(image: &[u8]) -> Result<CFRetained<CGImage>> {
    let data = CFData::from_bytes(image);
    // SAFETY: no options dictionary.
    let src = unsafe { CGImageSource::with_data(&data, None) }
        .ok_or_else(|| HandError::Other("not an image Quartz can decode".into()))?;
    // SAFETY: index 0 of a source; no options.
    unsafe { src.image_at_index(0, None) }
        .ok_or_else(|| HandError::Other("not an image Quartz can decode".into()))
}

/// An RGB bitmap (no alpha) holding the image, to draw on.
pub fn canvas(img: &CGImage, width: usize, height: usize) -> Result<CFRetained<CGContext>> {
    let space = CGColorSpace::new_device_rgb()
        .ok_or_else(|| HandError::Other("no RGB color space".into()))?;
    // SAFETY: CoreGraphics allocates the buffer (data NULL, bytes per row 0); 8 bits per component, RGBX.
    let ctx = unsafe {
        CGBitmapContextCreate(
            std::ptr::null_mut(),
            width,
            height,
            8,
            0,
            CFRetained::as_ptr(&space).as_ptr(),
            CGImageAlphaInfo::NoneSkipLast.0,
        )
    };
    let ctx = NonNull::new(ctx).ok_or_else(|| HandError::Other("couldn't make a bitmap".into()))?;
    // SAFETY: the Create rule: we own the context.
    let ctx = unsafe { CFRetained::from_raw(ctx) };
    CGContext::draw_image(
        Some(&ctx),
        rect(0.0, 0.0, width as f64, height as f64),
        Some(img),
    );
    Ok(ctx)
}

/// screenshot.py `_jpeg`: the image as JPEG bytes at JPEG_QUALITY.
pub fn jpeg(image: &CGImage) -> Result<Vec<u8>> {
    let data = CFMutableData::new(None, 0)
        .ok_or_else(|| HandError::Other("couldn't encode the screenshot".into()))?;
    let kind = CFString::from_static_str("public.jpeg");
    // SAFETY: a mutable data, a type identifier, one image, no options.
    let dest = unsafe { CGImageDestination::with_data(&data, &kind, 1, None) }
        .ok_or_else(|| HandError::Other("couldn't encode the screenshot".into()))?;
    // SAFETY: the exported key; a CFNumber value.
    let key: &CFString = unsafe { kCGImageDestinationLossyCompressionQuality };
    let q = CFNumber::new_f64(JPEG_QUALITY);
    let props = CFDictionary::<CFString, CFType>::from_slices(&[key], &[q.as_ref()]);
    // SAFETY: a destination made for one image; a properties dictionary of documented keys.
    unsafe { dest.add_image(image, Some(props.as_opaque())) };
    // SAFETY: finalize once, after the one image.
    if !unsafe { dest.finalize() } {
        return Err(HandError::Other("couldn't encode the screenshot".into()));
    }
    Ok(data.to_vec())
}

/// mask.py:116: the JPEG with each box filled opaque black, clamped to the image.
pub fn mask_secret_fields(image: &[u8], boxes: &[ImgBox]) -> Result<Vec<u8>> {
    objc2::rc::autoreleasepool(|_| {
        let img = decode(image)?;
        let (iw, ih) = (
            CGImage::width(Some(&img)) as i64,
            CGImage::height(Some(&img)) as i64,
        );
        let ctx = canvas(&img, iw as usize, ih as usize)?;
        CGContext::set_rgb_fill_color(Some(&ctx), 0.0, 0.0, 0.0, 1.0);
        for &(x, y, w, h) in boxes {
            let (left, top, right, bottom) = (x.max(0), y.max(0), (x + w).min(iw), (y + h).min(ih));
            if right > left && bottom > top {
                CGContext::fill_rect(
                    Some(&ctx),
                    rect(
                        left as f64,
                        (ih - bottom) as f64,
                        (right - left) as f64,
                        (bottom - top) as f64,
                    ),
                );
            }
        }
        let out = CGBitmapContextCreateImage(Some(&ctx))
            .ok_or_else(|| HandError::Other("couldn't paint".into()))?;
        jpeg(&out)
    })
}

/// mask.py:151: the image's width and height.
pub fn size(image: &[u8]) -> Result<(i64, i64)> {
    let img = decode(image)?;
    Ok((
        CGImage::width(Some(&img)) as i64,
        CGImage::height(Some(&img)) as i64,
    ))
}

/// The real painter.
pub struct NativePaint;

impl Paint for NativePaint {
    fn paint(&self, image: &[u8], boxes: &[ImgBox]) -> std::result::Result<Vec<u8>, String> {
        mask_secret_fields(image, boxes).map_err(|e| e.to_string())
    }
}

/// recording.py:677: decoded frames two to a row, 640x360 each, each outlined with a tag at its top-left. The time
/// label text is not drawn yet (Python draws it with CoreText): see the crate's open list.
pub struct NativeSheet;

impl crate::recording::ReviewSheet for NativeSheet {
    fn sheet(&self, frames: &[Vec<u8>], _times: &[f64]) -> Result<(Vec<u8>, i64, i64)> {
        objc2::rc::autoreleasepool(|_| {
            let width = frames.len().min(2) as i64 * 640;
            let height = ((frames.len() as i64 + 1) / 2) * 360;
            let space = CGColorSpace::new_device_rgb()
                .ok_or_else(|| HandError::Other("no RGB color space".into()))?;
            // SAFETY: CoreGraphics allocates; 8 bits per component, premultiplied RGBA.
            let ctx = unsafe {
                CGBitmapContextCreate(
                    std::ptr::null_mut(),
                    width as usize,
                    height as usize,
                    8,
                    0,
                    CFRetained::as_ptr(&space).as_ptr(),
                    CGImageAlphaInfo::PremultipliedLast.0,
                )
            };
            let ctx = NonNull::new(ctx)
                .ok_or_else(|| HandError::Other("couldn't make a bitmap".into()))?;
            // SAFETY: the Create rule.
            let ctx = unsafe { CFRetained::from_raw(ctx) };
            for (i, data) in frames.iter().enumerate() {
                let img = decode(data)?;
                let (x, y) = ((i as i64 % 2) * 640, (i as i64 / 2) * 360);
                let r = rect(x as f64, (height - y - 360) as f64, 640.0, 360.0);
                CGContext::draw_image(Some(&ctx), r, Some(&img));
                CGContext::set_rgb_stroke_color(Some(&ctx), 0.95, 0.15, 0.35, 0.9);
                CGContext::set_line_width(Some(&ctx), 2.0);
                CGContext::stroke_rect(Some(&ctx), r);
            }
            let out = CGBitmapContextCreateImage(Some(&ctx))
                .ok_or_else(|| HandError::Other("couldn't draw".into()))?;
            Ok((jpeg(&out)?, width, height))
        })
    }
}
