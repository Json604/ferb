//! `export.py`: the Markdown view of memory, regenerated from SQLite after every change: one file per subject, only
//! the items active now, owner-only permissions; files of subjects without items are removed.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

use ferb_memory::terms::{label, slug};
use ferb_memory::times;

use crate::items::Memory;
use crate::{Error, Result};

fn io(e: std::io::Error) -> Error {
    Error::Crash("OSError", e.to_string())
}

/// export.py:13 `export`.
pub fn export(memory: &Memory, folder: &Path) -> Result<Vec<PathBuf>> {
    fs::create_dir_all(folder).map_err(io)?;
    fs::set_permissions(folder, fs::Permissions::from_mode(0o700)).map_err(io)?;
    let mut by_subject: Vec<(String, Vec<String>)> = Vec::new();
    for it in memory.items(Some("active"), None, true)? {
        let line = format!(
            "- **{} · {}**: {}  \n  _{}, since {}, {} source(s), id {}_",
            it.kind,
            it.key,
            it.content,
            label(&it.origin),
            times::ymd(&it.valid_from),
            it.source_ids.len(),
            it.id
        );
        match by_subject.iter_mut().find(|(s, _)| *s == it.subject) {
            Some((_, lines)) => lines.push(line),
            None => by_subject.push((it.subject.clone(), vec![line])),
        }
    }
    by_subject.sort_by(|a, b| a.0.cmp(&b.0));
    let mut written = Vec::new();
    for (subject, lines) in &by_subject {
        let p = folder.join(format!("{}.md", slug(&subject.replace(':', "-"), Some(80))));
        let tmp = p.with_extension("tmp");
        let text = format!(
            "# {subject}\n\n_Generated by FERB from its database; edits here are not read back._\n\n{}\n",
            lines.join("\n")
        );
        fs::write(&tmp, text).map_err(io)?;
        fs::set_permissions(&tmp, fs::Permissions::from_mode(0o600)).map_err(io)?;
        fs::rename(&tmp, &p).map_err(io)?;
        written.push(p);
    }
    for entry in fs::read_dir(folder).map_err(io)? {
        let path = entry.map_err(io)?.path();
        if path.extension().is_some_and(|e| e == "md") && !written.contains(&path) {
            fs::remove_file(&path).map_err(io)?;
        }
    }
    Ok(written)
}
