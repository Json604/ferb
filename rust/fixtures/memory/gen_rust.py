"""Writes rust/crates/ferb-memory/src/generated.rs from the Python build: the Unicode facts Python 3.12 answers with
where the memory code reads text (str.isspace/lower/casefold/isprintable, unicodedata.category and normalize('NFD'),
the categories `query_terms` and `word_char` read, `\\w` and `\\d` in a str pattern), html.unescape's tables, and the
cp437 names zipfile gives a member. Called by make.py; never edit the output."""

import html
import html.entities
import re
import unicodedata
from pathlib import Path

from ferb.memory import items
from ferb.sanitize.redact import word_char

OUT = Path(__file__).resolve().parents[2] / "crates" / "ferb-memory" / "src" / "generated.rs"


def lit(s: str) -> str:
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return "".join(out) + '"'


def chars():
    for cp in range(0x110000):
        if not 0xD800 <= cp <= 0xDFFF:
            yield cp, chr(cp)


def ranges(pred) -> list[tuple[int, int]]:
    out, start, last = [], None, None
    for cp, c in chars():
        hit = pred(c)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, last))
            start = None
        last = cp
        if cp == 0xD7FF and start is not None:     # never let a range cross the surrogates
            out.append((start, cp))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name: str, pred, doc: str) -> str:
    body = "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in ranges(pred))
    return f"/// {doc}\npub static {name}: &[(u32, u32)] = &[\n{body}];\n\n"


def mapping(name: str, pairs: list[tuple[int, str]], doc: str) -> str:
    body = "".join(f"    (0x{cp:x}, {lit(s)}),\n" for cp, s in pairs)
    return f"/// {doc}\npub static {name}: &[(u32, &str)] = &[\n{body}];\n\n"


def hangul(c: str) -> str | None:
    s = ord(c) - 0xAC00
    if not 0 <= s < 11172:
        return None
    lead, vowel, trail = 0x1100 + s // 588, 0x1161 + (s % 588) // 28, 0x11A7 + s % 28
    return chr(lead) + chr(vowel) + (chr(trail) if trail != 0x11A7 else "")


def main() -> None:
    parts = ["// Generated by rust/fixtures/memory/gen_rust.py (run through make.py) from the Python build.\n"
             "// Do not edit: regenerate.\n"
             f"// Python's Unicode data: {unicodedata.unidata_version}.\n\n"]
    cat = unicodedata.category
    parts.append(table("SPACE", str.isspace, "str.isspace(), which is also `\\s` in a str pattern."))
    assert ranges(lambda c: re.match(r"\s", c) is not None) == ranges(str.isspace)
    parts.append(table("CAT_C", lambda c: cat(c).startswith("C"),
                       "unicodedata.category(c) starts with \"C\" (control, format, unassigned, private use)."))
    parts.append(table("CAT_P", lambda c: cat(c).startswith("P"), "unicodedata.category(c) starts with \"P\"."))
    parts.append(table("CAT_MN", lambda c: cat(c) == "Mn", "unicodedata.category(c) == \"Mn\"."))
    terms = lambda c: cat(c)[0] in "LNM" or cat(c) == "Co"     # noqa: E731 (items.query_terms' rule)
    assert ranges(terms) == ranges(word_char)
    assert items.query_terms("Ab1́ x") == ["ab1́", "x"]
    parts.append(table("WORD", word_char, "redact.word_char and query_terms' rule: category L*, N*, M* or Co."))
    parts.append(table("RE_WORD", lambda c: re.match(r"\w", c) is not None, "`\\w` in a str pattern."))
    parts.append(table("NOT_PRINTABLE", lambda c: not c.isprintable(), "Characters repr() writes as an escape."))
    runs = []
    for a, b in ranges(str.isdecimal):
        for start in range(a, b + 1):
            if unicodedata.decimal(chr(start)) == 0:
                end = start
                while end + 1 <= b and unicodedata.decimal(chr(end + 1)) == end + 1 - start:
                    end += 1
                runs.append((start, end))
    assert sum(b - a + 1 for a, b in runs) == sum(b - a + 1 for a, b in ranges(str.isdecimal))
    for a, b in runs:
        assert all(unicodedata.decimal(chr(cp)) == cp - a for cp in range(a, b + 1)), (a, b)
    parts.append("/// str.isdecimal() (`\\d` in a str pattern), in runs whose first character is the digit 0.\n"
                 "pub static DECIMAL: &[(u32, u32)] = &[\n"
                 + "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in runs) + "];\n\n")
    sigma = "Σ"
    parts.append(table("CASE_IGNORABLE",
                       lambda c: ("a" + c + sigma).lower()[-1] == "ς" and (c + sigma).lower()[-1] != "ς",
                       "Characters str.lower() skips around a capital sigma (case-ignorable)."))
    parts.append(table("CASED", lambda c: (c + sigma).lower()[-1] == "ς",
                       "Cased characters that aren't case-ignorable (a capital sigma after one may be final)."))
    parts.append(mapping("LOWER", [(cp, c.lower()) for cp, c in chars() if c.lower() != c and cp != 0x3A3],
                         "str.lower() for every character it changes (the capital sigma aside: see CASED)."))
    parts.append(mapping("CASEFOLD", [(cp, c.casefold()) for cp, c in chars() if c.casefold() != c],
                         "str.casefold() for every character it changes."))
    nfd = []
    for cp, c in chars():
        d = unicodedata.normalize("NFD", c)
        if hangul(c) is not None:
            assert d == hangul(c), cp
        elif d != c:
            nfd.append((cp, d))
    parts.append(mapping("NFD", nfd, "unicodedata.normalize('NFD', c) for every character it changes but the Hangul "
                                     "syllables (decomposed by rule in unicode.rs)."))
    ccc = [(cp, unicodedata.combining(c)) for cp, c in chars() if unicodedata.combining(c)]
    parts.append("/// unicodedata.combining(c) for every character whose class isn't 0.\n"
                 "pub static CCC: &[(u32, u8)] = &[\n" + "".join(f"    (0x{cp:x}, {n}),\n" for cp, n in ccc) + "];\n\n")
    ents = sorted(html.entities.html5.items())
    parts.append("/// html.entities.html5, sorted by name (html.unescape's named references).\n"
                 "pub static HTML5: &[(&str, &str)] = &[\n"
                 + "".join(f"    ({lit(k)}, {lit(v)}),\n" for k, v in ents) + "];\n\n")
    parts.append("/// html._invalid_charrefs (html/__init__.py).\npub static INVALID_CHARREFS: &[(u32, &str)] = &[\n"
                 + "".join(f"    (0x{k:x}, {lit(v)}),\n" for k, v in sorted(html._invalid_charrefs.items())) + "];\n\n")
    parts.append("/// html._invalid_codepoints (html/__init__.py).\npub static INVALID_CODEPOINTS: &[u32] = &[\n"
                 + "".join(f"    0x{k:x},\n" for k in sorted(html._invalid_codepoints)) + "];\n\n")
    high = bytes(range(128, 256)).decode("cp437")
    parts.append(f"/// bytes 0x80..=0xff in cp437 (zipfile's member names without the UTF-8 flag).\n"
                 f"pub static CP437_HIGH: &str = {lit(high)};\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
