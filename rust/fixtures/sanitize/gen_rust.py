"""Writes rust/crates/ferb-sanitize/src/generated.rs from the Python build: the source of every compiled pattern in
ferb/sanitize (so the Rust port translates the same text Python compiles) and the Unicode facts Python 3.12 answers
with (str.isspace, isalnum, unicodedata.category, casefold). Called by make.py; never edit the output."""

import re
import unicodedata
from pathlib import Path

from ferb.sanitize import formats, known, labels, redact, stream, untrusted

OUT = Path(__file__).resolve().parents[2] / "crates" / "ferb-sanitize" / "src" / "generated.rs"


def lit(s: str) -> str:
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return "".join(out) + '"'


def ranges(pred) -> list[tuple[int, int]]:
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:                  # never a Rust char; kept out so a range can't cross them
            hit = False
        else:
            hit = pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name: str, pred, doc: str) -> str:
    rs = ranges(pred)
    body = "".join(f"    (0x{a:x}, 0x{b:x}),\n" for a, b in rs)
    return f"/// {doc}\npub static {name}: &[(u32, u32)] = &[\n{body}];\n\n"


def patterns() -> list[tuple[str, re.Pattern[str]]]:
    out: list[tuple[str, re.Pattern[str]]] = []
    skip = {"_EXACT_NEEDLES", "_FOLDED_NEEDLES", "_ALNUM", "_NOT_ALNUM", "_MARKERS"}   # ported by hand (see rx.rs)
    seen: set[int] = set()
    for mod in (formats, known, labels, stream, untrusted, redact):
        prefix = mod.__name__.rsplit(".", 1)[1].upper()
        for key, value in vars(mod).items():
            if isinstance(value, re.Pattern) and key not in skip and id(value) not in seen:
                seen.add(id(value))
                out.append((f"{prefix}_{key.strip('_')}", value))
    names = {'"': "DQ", "'": "SQ", "`": "BT", '\\"': "EDQ", "\\'": "ESQ"}
    for q, p in formats._QUOTED.items():
        out.append((f"FORMATS_QUOTED_{names[q]}", p))
    for q, p in labels._VALUE_QUOTES.items():
        out.append((f"LABELS_VALUE_QUOTES_{names[q]}", p))
    for q, p in labels._QUOTE_CLOSE.items():
        out.append((f"LABELS_QUOTE_CLOSE_{names[q]}", p))
    return out


def main() -> None:
    parts = ["// Generated by rust/fixtures/sanitize/gen_rust.py (run through make.py) from the Python build.\n"
             "// Do not edit: change ferb/sanitize and regenerate.\n"
             f"// Python's Unicode data: {unicodedata.unidata_version}.\n\n"
             "/// A Python pattern as `re` compiled it: its source text and its flags (re.I = 2, re.M = 8, re.S = 16,\n"
             "/// re.X = 64).\npub struct Pat {\n    pub name: &'static str,\n    pub src: &'static str,\n"
             "    pub flags: u32,\n}\n\n"]
    all_names = []
    for name, p in patterns():
        flags = int(p.flags & (re.I | re.M | re.S | re.X))
        parts.append(f"pub static {name}: Pat = Pat {{\n    name: {lit(name)},\n    src: {lit(p.pattern)},\n"
                     f"    flags: {flags},\n}};\n")
        all_names.append(name)
    parts.append("\npub static ALL_PATTERNS: &[&Pat] = &[\n" + "".join(f"    &{n},\n" for n in all_names) + "];\n\n")

    # formats.TABLE in its written order (Discord's entry included, as SECRET_PATTERNS has it).
    groups = {kind: group for kind, _, group in [*formats.TABLE, formats._DISCORD]}
    kinds = list(formats.NEEDLES)
    assert len(kinds) == len(formats.SECRET_PATTERNS)
    parts.append("/// formats.TABLE as written (formats.py:26-59): kind, pattern, flags, masked group, needles, whether\n"
                 "/// the needles are read on the lowercased text.\n"
                 "pub struct Format {\n    pub kind: &'static str,\n    pub pat: Pat,\n    pub group: usize,\n"
                 "    pub needles: &'static [&'static str],\n    pub folded: bool,\n}\n\n"
                 "pub static FORMAT_TABLE: &[Format] = &[\n")
    for kind, p in zip(kinds, formats.SECRET_PATTERNS):
        needles, folded = formats.NEEDLES[kind]
        flags = int(p.flags & (re.I | re.M | re.S | re.X))
        parts.append(f"    Format {{\n        kind: {lit(kind)},\n        pat: Pat {{\n            name: {lit(kind)},\n"
                     f"            src: {lit(p.pattern)},\n            flags: {flags},\n        }},\n"
                     f"        group: {groups[kind]},\n        needles: &[{', '.join(lit(n) for n in needles)}],\n"
                     f"        folded: {'true' if folded else 'false'},\n    }},\n")
    parts.append("];\n\n")
    exact = sorted({n for ns, folded in formats.NEEDLES.values() if not folded for n in ns if n}, key=len, reverse=True)
    fold = sorted({n for ns, folded in formats.NEEDLES.values() if folded for n in ns}, key=len, reverse=True)
    assert "|".join(re.escape(n) for n in exact).count("|") == formats._EXACT_NEEDLES.pattern.count("|")
    exact.sort(key=lambda n: (-len(n), n))          # same length, same start: at most one can match, so order is free
    fold.sort(key=lambda n: (-len(n), n))
    parts.append("/// formats._EXACT_NEEDLES's alternatives, longest first (formats.py:77).\n"
                 f"pub static EXACT_NEEDLES: &[&str] = &[{', '.join(lit(n) for n in exact)}];\n\n"
                 "/// formats._FOLDED_NEEDLES's alternatives, longest first (formats.py:81).\n"
                 f"pub static FOLDED_NEEDLES: &[&str] = &[{', '.join(lit(n) for n in fold)}];\n\n"
                 "/// formats._IMPLIED (formats.py:80): each needle with the needles inside it.\n"
                 "pub static IMPLIED: &[(&str, &[&str])] = &[\n")
    for n, inside in sorted(formats._IMPLIED.items()):
        parts.append(f"    ({lit(n)}, &[{', '.join(lit(m) for m in sorted(inside))}]),\n")
    parts.append("];\n\n")

    parts.append(table("SPACE", str.isspace, "str.isspace(), which is also `\\s` in a str pattern."))
    parts.append(table("DECIMAL", str.isdecimal, "str.isdecimal(), which is `\\d` in a str pattern."))
    # DIGIT, NOT_PRINTABLE, CASE_IGNORABLE, CASED, LOWER and NFKC_DELIMS live in ferb-py now (rust/fixtures/py/make_unicode.py
    # makes them with this file's `table`), with the helpers that read them (`ferb_py::text`, `ferb_py::url`)
    parts.append(table("ALPHA", str.isalpha, "str.isalpha()."))
    parts.append(table("ALNUM", str.isalnum, "str.isalnum(); with \"_\" it is `\\w` in a str pattern."))
    assert ranges(lambda c: re.match(r"\w", c) is not None) == ranges(lambda c: c.isalnum() or c == "_")
    assert ranges(lambda c: re.match(r"\d", c) is not None) == ranges(str.isdecimal)
    assert ranges(lambda c: re.match(r"\s", c) is not None) == ranges(str.isspace)
    parts.append(table("WORD_CHAR", known.word_char, "known.word_char (known.py:31): category L*, N*, M* or Co."))
    parts.append(table("ESCAPED", lambda c: unicodedata.category(c) in untrusted._ESCAPED,
                       "untrusted._ESCAPED (untrusted.py:105): category Cf, Co, Cc, Zl, Zp (Cs can't be a Rust char)."))
    parts.append(table("UPPER", str.isupper, "Characters str.isupper() counts as uppercase."))
    parts.append(table("LOWER_OR_TITLE", lambda c: c.islower() or unicodedata.category(c) == "Lt",
                       "Characters that make str.isupper() false: lowercase or titlecase."))
    folds = [(cp, chr(cp).casefold()) for cp in range(0x110000)
             if not 0xD800 <= cp <= 0xDFFF and chr(cp).casefold() != chr(cp)]
    parts.append("/// str.casefold() for every character it changes.\npub static CASEFOLD: &[(u32, &str)] = &[\n"
                 + "".join(f"    (0x{cp:x}, {lit(f)}),\n" for cp, f in folds) + "];\n")
    OUT.write_text("".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
