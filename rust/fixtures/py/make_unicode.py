"""Writes rust/crates/ferb-py/src/unicode_str.rs from Python 3.12's own answers: the Unicode facts behind
`str.isspace`, `str.isdigit`, `str.isalnum`, `str.isprintable` (what `repr` escapes), `str.lower` (with the capital
sigma's rule) and the characters urllib's netloc check refuses, for the one copy of those helpers
(rust/crates/ferb-py/src/text.rs and url.rs). The tables are made exactly as rust/fixtures/sanitize/gen_rust.py made
them (its `ranges`, `table` and `lit` are used here), so the move changed no answer. Never edit the output.

Run from the repo root:  uv run python rust/fixtures/py/make_unicode.py
"""

import importlib.util
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "crates" / "ferb-py" / "src" / "unicode_str.rs"
sys.path.insert(0, str(HERE.parents[2]))

spec = importlib.util.spec_from_file_location("gen_rust", HERE.parent / "sanitize" / "gen_rust.py")
assert spec is not None and spec.loader is not None
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)


def main() -> None:
    sigma = "Σ"
    parts = ["// Generated by rust/fixtures/py/make_unicode.py from Python "
             f"{sys.version_info.major}.{sys.version_info.minor}'s own answers. Do not edit.\n\n"]
    parts.append(gen.table("SPACE", str.isspace, "str.isspace(), which is also `\\s` in a str pattern."))
    parts.append(gen.table("DIGIT", str.isdigit, "str.isdigit()."))
    parts.append(gen.table("ALNUM", str.isalnum, "str.isalnum(); with \"_\" it is `\\w` in a str pattern."))
    parts.append(gen.table("NOT_PRINTABLE", lambda c: not c.isprintable(), "Characters repr() writes as an escape."))
    parts.append(gen.table("CASE_IGNORABLE",
                           lambda c: ("a" + c + sigma).lower()[-1] == "ς" and (c + sigma).lower()[-1] != "ς",
                           "Characters str.lower() skips around a capital sigma (case-ignorable)."))
    parts.append(gen.table("CASED", lambda c: (c + sigma).lower()[-1] == "ς",
                           "Cased characters that aren't case-ignorable (a capital sigma after one may be final)."))
    # urllib.parse._checknetloc refuses a host whose NFKC form holds one of "/?#@:"; those five never combine with a
    # following mark (checked here), so the check is per character
    delims = "/?#@:"
    for d in delims:
        for cp in range(0x110000):
            if not 0xD800 <= cp <= 0xDFFF and unicodedata.combining(chr(cp)):
                assert unicodedata.normalize("NFKC", d + chr(cp))[0] == d, (d, cp)
    parts.append(gen.table("NFKC_DELIMS", lambda c: c not in delims and any(d in unicodedata.normalize("NFKC", c)
                                                                             for d in delims),
                           "Characters whose NFKC form holds one of \"/?#@:\" (urllib.parse._checknetloc)."))
    lowers = [(cp, chr(cp).lower()) for cp in range(0x110000)
              if not 0xD800 <= cp <= 0xDFFF and chr(cp).lower() != chr(cp) and cp != 0x3A3]
    parts.append("/// str.lower() for every character it changes (the capital sigma aside: see CASED).\n"
                 "pub static LOWER: &[(u32, &str)] = &[\n"
                 + "".join(f"    (0x{cp:x}, {gen.lit(f)}),\n" for cp, f in lowers) + "];\n")
    OUT.write_text("".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
