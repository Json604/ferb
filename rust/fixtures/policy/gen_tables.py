"""Writes rust/crates/ferb-policy/src/tables.rs from the Python build: the Unicode facts Python 3.12 answers with
(str.isspace/isdecimal/isdigit/isalpha/isalnum/isupper/isprintable, lower, casefold, unicodedata.category,
bidirectional, combining, name, normalize) and the idna package's tables (UTS #46 mapping, IDNA 2008 classes, joining
types, scripts), so ferb-policy reads text exactly as ferb/policy does whatever Unicode version Rust has. Called by
make.py; never edit the output."""

import unicodedata
from pathlib import Path

import idna
import idna.idnadata as idnadata
import idna.uts46data as uts46data

OUT = Path(__file__).resolve().parents[2] / "crates" / "ferb-policy" / "src" / "tables.rs"
SURROGATES = range(0xD800, 0xE000)


def lit(s: str) -> str:
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return "".join(out) + '"'


def chars():
    for cp in range(0x110000):
        if cp not in SURROGATES:
            yield cp, chr(cp)


def ranges(pred) -> list[tuple[int, int]]:
    out, start = [], None
    for cp in range(0x110000):
        hit = cp not in SURROGATES and pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def rows(items: list[str], per: int = 8) -> str:
    return "".join("    " + " ".join(items[i:i + per]) + "\n" for i in range(0, len(items), per))


def table(name: str, pred, doc: str) -> str:
    rs = ranges(pred)
    return f"/// {doc}\npub static {name}: &[(u32, u32)] = &[\n" + rows([f"(0x{a:x}, 0x{b:x})," for a, b in rs]) + "];\n\n"


def valued(name: str, fn, doc: str) -> str:
    """Ranges of equal non-empty value: (start, end, value)."""
    out, start, cur = [], None, None
    for cp in range(0x110001):
        v = fn(chr(cp)) if cp < 0x110000 and cp not in SURROGATES else None
        if v != cur:
            if cur:
                out.append((start, cp - 1, cur))
            start, cur = cp, v
    kind = "&str" if isinstance(next((v for _, _, v in out), ""), str) else "u8"
    body = [f"(0x{a:x}, 0x{b:x}, {lit(v) if kind == '&str' else v})," for a, b, v in out]
    return f"/// {doc}\npub static {name}: &[(u32, u32, {kind})] = &[\n" + rows(body, 4) + "];\n\n"


def mapping(name: str, items: list[tuple[int, str]], doc: str) -> str:
    return (f"/// {doc}\npub static {name}: &[(u32, &str)] = &[\n"
            + rows([f"(0x{cp:x}, {lit(v)})," for cp, v in items], 4) + "];\n\n")


def intranges(name: str, values, doc: str) -> str:
    pairs = [(v >> 32, v & 0xFFFFFFFF) for v in values]
    return (f"/// {doc} (start, end exclusive)\npub static {name}: &[(u32, u32)] = &[\n"
            + rows([f"(0x{a:x}, 0x{b:x})," for a, b in pairs]) + "];\n\n")


def main() -> None:
    parts = ["// Generated by rust/fixtures/policy/gen_tables.py (run through make.py) from the Python build.\n"
             "// Do not edit: regenerate.\n"
             f"// Python's Unicode data: {unicodedata.unidata_version}; idna {idna.__version__}.\n\n"]
    parts.append(table("SPACE", str.isspace, "str.isspace(), which is also `\\s` in a str pattern."))
    dec = ranges(str.isdecimal)
    for a, b in dec:           # each run of decimal digits starts at a zero and holds whole tens
        assert unicodedata.decimal(chr(a)) == 0 and (b - a + 1) % 10 == 0, (a, b)
    parts.append(table("DECIMAL", str.isdecimal, "str.isdecimal() (`\\d`): runs of whole tens, each from a zero."))
    parts.append(table("DIGIT", str.isdigit, "str.isdigit()."))
    parts.append(table("ALPHA", str.isalpha, "str.isalpha()."))
    parts.append(table("ALNUM", str.isalnum, "str.isalnum(); with \"_\" it is `\\w` in a str pattern."))
    parts.append(table("UPPER", str.isupper, "Characters str.isupper() takes alone."))
    parts.append(table("NOT_PRINTABLE", lambda c: not c.isprintable(), "Characters str.isprintable() refuses."))
    cat = unicodedata.category
    parts.append(table("MARK", lambda c: cat(c)[0] == "M", "unicodedata.category M*."))
    parts.append(table("MN", lambda c: cat(c) == "Mn", "unicodedata.category Mn."))
    parts.append(table("CF", lambda c: cat(c) == "Cf", "unicodedata.category Cf."))
    parts.append(table("SC", lambda c: cat(c) == "Sc", "unicodedata.category Sc."))
    parts.append(table("LN", lambda c: cat(c)[0] in "LN", "unicodedata.category L* or N*."))
    parts.append(table("CO", lambda c: cat(c) == "Co", "unicodedata.category Co."))
    parts.append(table("NO_NAME", lambda c: unicodedata.name(c, None) is None, "unicodedata.name raises."))
    sigma = "Σ"
    parts.append(table("CASE_IGNORABLE",
                       lambda c: ("a" + c + sigma).lower()[-1] == "ς" and (c + sigma).lower()[-1] != "ς",
                       "Characters str.lower() skips around a capital sigma (case-ignorable)."))
    parts.append(table("CASED", lambda c: (c + sigma).lower()[-1] == "ς",
                       "Cased characters that aren't case-ignorable (a capital sigma after one may be final)."))
    parts.append(mapping("LOWER", [(cp, c.lower()) for cp, c in chars() if c.lower() != c and cp != 0x3A3],
                         "str.lower() for every character it changes (the capital sigma aside)."))
    parts.append(mapping("UPPER_MAP", [(cp, c.upper()) for cp, c in chars() if c.upper() != c],
                         "str.upper() for every character it changes."))
    parts.append(mapping("CAPITALIZE", [(cp, c.capitalize()) for cp, c in chars() if c.capitalize() != c],
                         "str.capitalize() of one character, for every character it changes."))
    parts.append(mapping("CASEFOLD", [(cp, c.casefold()) for cp, c in chars() if c.casefold() != c],
                         "str.casefold() for every character it changes."))
    parts.append(valued("BIDI", lambda c: unicodedata.bidirectional(c), "unicodedata.bidirectional ('' left out)."))
    parts.append(valued("CCC", lambda c: unicodedata.combining(c), "unicodedata.combining (0 left out)."))
    hangul = range(0xAC00, 0xD7A4)
    parts.append(mapping("NFD", [(cp, unicodedata.normalize("NFD", c)) for cp, c in chars()
                                 if cp not in hangul and unicodedata.normalize("NFD", c) != c],
                         "A character's canonical decomposition, full and ordered (Hangul syllables aside)."))
    parts.append(mapping("NFKD", [(cp, unicodedata.normalize("NFKD", c)) for cp, c in chars()
                                  if cp not in hangul and unicodedata.normalize("NFKD", c) != c],
                         "A character's compatibility decomposition, full and ordered (Hangul syllables aside)."))
    pairs = []
    for cp, c in chars():
        d = unicodedata.decomposition(c)
        if d and not d.startswith("<") and cp not in hangul:
            ab = [int(x, 16) for x in d.split()]
            if len(ab) == 2 and unicodedata.normalize("NFC", c) == c:
                pairs.append((ab[0], ab[1], cp))
    pairs.sort()
    parts.append("/// Canonical compositions: (first, second, composite), sorted (Hangul aside).\n"
                 "pub static COMPOSE: &[(u32, u32, u32)] = &[\n"
                 + rows([f"(0x{a:x}, 0x{b:x}, 0x{c:x})," for a, b, c in pairs], 4) + "];\n\n")
    starts = list(uts46data.uts46_starts)
    statuses = uts46data.uts46_statuses
    reps = uts46data.uts46_replacements
    parts.append("/// idna's UTS #46 table: (first code point, status byte, replacement; \"\" for none).\n"
                 "pub static UTS46: &[(u32, u8, &str)] = &[\n"
                 + rows([f"(0x{s:x}, {statuses[i]}, {lit(reps[i] or '')})," for i, s in enumerate(starts)], 4)
                 + "];\n\n")
    for cls in ("PVALID", "CONTEXTJ", "CONTEXTO"):
        parts.append(intranges(f"IDNA_{cls}", idnadata.codepoint_classes[cls], f"idnadata.codepoint_classes {cls}"))
    order = list(idnadata.joining_types)
    parts.append(f"/// The joining types in idnadata's order.\npub static JOINING_ORDER: &[char] = &[{', '.join(repr(k) for k in order)}];\n\n")
    for jt in order:
        parts.append(intranges(f"JOINING_{jt}", idnadata.joining_types[jt], f"idnadata.joining_types {jt}"))
    for script in ("Greek", "Han", "Hebrew", "Hiragana", "Katakana"):
        parts.append(intranges(f"SCRIPT_{script.upper()}", idnadata.scripts[script], f"idnadata.scripts {script}"))
    OUT.write_text("".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
