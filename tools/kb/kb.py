def write_html(kb: KB) -> Path:
    out = kb.root / kb.cfg["html_path"]
    out.parent.mkdir(parents=True, exist_ok=True)
    data = json.dumps(kb.data(), default=as_text).replace("</", "<\\/")
    out.write_text(HTML_TEMPLATE.replace("__DATA__", data))
    return out


