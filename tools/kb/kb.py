"""kb.py: the repository's knowledge registry (installed by the repo-kb skill).

Decisions, the work list, live (manual) checks and terms live as small TOML records under kb/. This script checks
them, answers "what governs this file / this ID?", and generates the map. It is deterministic: the same files always
give the same answer, and it never calls a model. Stdlib only, Python 3.11+ (run it through tools/kb/run).

    tools/kb/run kb check                 # validate everything (the gate runs this)
    tools/kb/run kb show path/to/file.py  # what governs a file: decisions, tests, open work, live checks
    tools/kb/run kb show AUTH-3           # one record and everything linked to it, plus its git history
    tools/kb/run kb next                  # ready work, questions for the owner first
    tools/kb/run kb gen [--html]          # regenerate kb/MAP.md (and the local visual page)
"""

