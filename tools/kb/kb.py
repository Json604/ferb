def md_units(text: str) -> list[dict]:
    """Every block of a Markdown file: headings, top-level list items, paragraphs, table rows, code blocks."""
    units, heads = [], []
    in_code = para = False
    for n, raw in enumerate(text.splitlines(), 1):
        line = raw.rstrip()
        s = line.strip()
        if s.startswith("```") or s.startswith("~~~"):
            if not in_code:
                units.append({"line": n, "text": norm_text(line) or "code block", "kind": "code",
                              "section": list(heads)})
            in_code, para = not in_code, False
            continue
        if in_code:
            continue
        if not s:
            para = False
            continue
        m = re.match(r"^(#{1,6})\s+(.*)", line)
        if m:
            level = len(m.group(1))
            heads = [h for h in heads if h[0] < level] + [(level, norm_text(m.group(2)))]
            units.append({"line": n, "text": norm_text(m.group(2)), "kind": "heading", "section": list(heads)})
            para = False
            continue
        if re.match(r"^ ?([-*+]|\d+[.)])\s+", line):
            units.append({"line": n, "text": norm_text(line), "kind": "item", "section": list(heads)})
            para = True
            continue
        if s.startswith("|"):
            if not re.fullmatch(r"[|:\-\s]+", s):
                units.append({"line": n, "text": norm_text(s), "kind": "row", "section": list(heads)})
            continue
        if para:
            continue
        units.append({"line": n, "text": norm_text(line), "kind": "para", "section": list(heads)})
        para = True
    return units


def reconcile_path(kb: KB, src: str) -> Path:
    return kb.root / kb.cfg["reconcile_dir"] / (src.replace("/", "__") + ".toml")


def item_covers(item: dict, unit: dict) -> bool:
    if item.get("section"):
        raw = str(item["section"]).strip()
        secs = [x for x in dict.fromkeys((raw.lower(), norm_text(raw))) if x]   # as `init` wrote it, or normalized once
        return any(h[1].startswith(sec) for h in unit["section"] for sec in secs)
    raw = str(item.get("src", "")).strip()
    # `init` writes src already normalized; normalizing it again would strip a leading "#" from a "| # |" table row
    for src in dict.fromkeys((raw, norm_text(raw))):
        if src and unit["text"].startswith(src) and len(src) >= min(20, len(unit["text"])):
            return True
    return False


def reconcile_problems(kb: KB, src: str) -> list[str]:
    p = kb.root / src
    if not p.exists():
        return [f"{src} does not exist"]
    rp = reconcile_path(kb, src)
    if not rp.exists():
        return [f"{kb.rel(rp)} does not exist: run `kb reconcile init {src}`"]
    doc = kb._toml(rp)
    items = doc.get("item", [])
    out = list(kb.errors)
    ids = kb.all_ids()
    for n, it in enumerate(items, 1):
        how = it.get("how", "")
        where = f"{kb.rel(rp)} item {n} ({str(it.get('src') or it.get('section', ''))[:40]!r})"
        if how not in RECONCILE_HOW:
            out.append(f"{where}: `how` must be one of {', '.join(sorted(RECONCILE_HOW))}")
            continue
        to = it.get("to", [])
        to = [to] if isinstance(to, str) else to
        if how in ("dropped", "kept", "code") and not it.get("reason"):
            out.append(f"{where}: `{how}` needs a `reason`")
        if how in ("decision", "task", "live", "merged", "question"):
            if not to:
                out.append(f"{where}: `{how}` needs `to` (the new IDs)")
            for x in to:
                if x not in ids:
                    out.append(f"{where}: `to` {x} does not exist in kb/")
        if how == "term":
            for x in to:
                if x not in kb.glossary:
                    out.append(f"{where}: term {x!r} is not in kb/glossary.toml")
    units = md_units(p.read_text(encoding="utf-8", errors="replace"))
    used = [False] * len(items)
    for u in units:
        hit = False
        for i, it in enumerate(items):
            if item_covers(it, u):
                used[i] = hit = True
        if not hit:
            out.append(f"{src}:{u['line']}: not accounted for: {u['text'][:90]!r}")
    for i, it in enumerate(items):
        if not used[i]:
            out.append(f"{kb.rel(rp)} item {i + 1}: matches nothing in {src} (typo?)")
    return out


def reconcile_init(kb: KB, src: str) -> Path:
    p = kb.root / src
    if not p.exists():
        sys.exit(f"kb.py: {src} does not exist")
    rp = reconcile_path(kb, src)
    if rp.exists():
        sys.exit(f"kb.py: {kb.rel(rp)} already exists")
    rp.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# Where each block of {src} went. Fill `how` (+ `to` or `reason`) for every item; an item with",
             "# `section = \"heading\"` instead of `src` covers that whole section (e.g. a dated history to drop).",
             "# how: decision | task | live | term | merged | question | dropped | kept | code",
             f'source = "{src}"', 'approved_by = ""', 'approved_on = ""', ""]
    for u in md_units(p.read_text(encoding="utf-8", errors="replace")):
        key = u["text"][:70].replace("\\", "\\\\").replace('"', '\\"')
        lines += ["[[item]]", f"# line {u['line']} ({u['kind']})", f'src = "{key}"', 'how = ""', "to = []",
                  'reason = ""', ""]
    rp.write_text("\n".join(lines))
    return rp


