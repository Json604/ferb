# ---------------------------------------------------------------- helpers

def run_git(root: Path, *args: str, check: bool = True) -> str:
    r = subprocess.run(["git", *args], cwd=root, capture_output=True, text=True)
    if check and r.returncode:
        raise SystemExit(f"kb.py: git {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout


def find_root(start: Path | None = None) -> Path:
    r = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=start or Path.cwd(), capture_output=True, text=True)
    if r.returncode:
        sys.exit("kb.py: not inside a git repository")
    return Path(r.stdout.strip())


_GLOB_CACHE: dict[str, re.Pattern] = {}


def glob_re(pat: str) -> re.Pattern:
    """`**/` = any folders (or none), `**` = anything, `*` = within one folder, `?` = one character."""
    if pat in _GLOB_CACHE:
        return _GLOB_CACHE[pat]
    out, i = [], 0
    while i < len(pat):
        if pat.startswith("**/", i):
            out.append("(?:.*/)?"); i += 3
        elif pat.startswith("**", i):
            out.append(".*"); i += 2
        elif pat[i] == "*":
            out.append("[^/]*"); i += 1
        elif pat[i] == "?":
            out.append("[^/]"); i += 1
        else:
            out.append(re.escape(pat[i])); i += 1
    _GLOB_CACHE[pat] = rx = re.compile("^" + "".join(out) + "$")
    return rx


def path_matches(entry: str, path: str) -> bool:
    """A `paths` entry: a glob, a file, or a folder (everything under it). `file.py::symbol` names a symbol."""
    entry = entry.split("::", 1)[0].strip().removeprefix("./")
    if not entry:
        return False
    if GLOB_CHARS & set(entry):
        return bool(glob_re(entry).match(path))
    entry = entry.rstrip("/")
    return path == entry or path.startswith(entry + "/")


def any_match(globs: list[str], path: str) -> bool:
    return any(path_matches(g, path) for g in globs)


def norm_text(s: str) -> str:
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)
    s = re.sub(r"^\s*(?:#{1,6}|>|\||[-*+]|\d+[.)])(?=\s|$)\s*", "", s)   # a marker is followed by a space ("0.27.0" stays)
    s = re.sub(r"[*_`~|]", "", s)
    return re.sub(r"\s+", " ", s).strip().lower()


def as_text(v) -> str:
    if isinstance(v, (dt.date, dt.datetime)):
        return v.isoformat()
    return "" if v is None else str(v)


@dataclass
class Tag:
    file: str
    line: int
    id: str
    test: bool


# ---------------------------------------------------------------- the registry

class KB:
    def __init__(self, root: Path):
        self.root = root
        self.dir = root / "kb"
        self.errors: list[str] = []
        self.cfg = self._config()
        self.areas: dict[str, dict] = {}
        self.decisions: dict[str, dict] = {}
        self.tasks: dict[str, dict] = {}
        self.live: dict[str, dict] = {}
        self.glossary: dict[str, dict] = {}
        self._files: list[str] | None = None
        self._tags: list[Tag] | None = None
        self._text: dict[str, str | None] = {}
        self._load()

    # loading ----------------------------------------------------------
    def _toml(self, path: Path) -> dict:
        if not path.exists():
            return {}
        try:
            return tomllib.loads(path.read_text(encoding="utf-8"))
        except (tomllib.TOMLDecodeError, UnicodeDecodeError) as e:
            self.errors.append(f"{self.rel(path)}: not valid TOML: {e}")
            return {}

    def rel(self, path: Path) -> str:
        try:
            return path.relative_to(self.root).as_posix()
        except ValueError:
            return str(path)

    def _config(self) -> dict:
        cfg = json.loads(json.dumps(DEFAULT_CONFIG))
        raw = self._toml(self.dir / "config.toml").get("kb", {})
        limits = raw.pop("limits", {})
        unknown = set(raw) - set(cfg)
        if unknown:
            self.errors.append(f"kb/config.toml: unknown settings {sorted(unknown)}")
        cfg.update({k: v for k, v in raw.items() if k in cfg})
        cfg["limits"].update(limits)
        return cfg

    def _put(self, store: dict, kind: str, ident: str, data, src: Path, local: bool, extra: dict | None = None):
        if not isinstance(data, dict):
            self.errors.append(f"{self.rel(src)}: [{ident}] must be a table")
            return
        if ident in store:
            self.errors.append(f"{self.rel(src)}: {kind} {ident} is defined twice (also in {store[ident]['_src']})")
            return
        rec = dict(data)
        rec.update({"_src": self.rel(src), "_local": local, "_kind": kind, **(extra or {})})
        store[ident] = rec

    def _load(self):
        for local in (False, True):
            base = self.dir / "local" if local else self.dir
            p = base / "areas.toml"
            for k, v in self._toml(p).items():
                self._put(self.areas, "area", k, v, p, local)
            ddir = base / "decisions"
            for p in sorted(ddir.glob("*.toml")) if ddir.is_dir() else []:
                for k, v in self._toml(p).items():
                    self._put(self.decisions, "decision", k, v, p, local, {"_area": p.stem})
            p = base / "tasks.toml"
            for k, v in self._toml(p).items():
                self._put(self.tasks, "task", k, v, p, local)
            p = base / "live.toml"
            for k, v in self._toml(p).items():
                self._put(self.live, "live", k, v, p, local)
            p = base / "glossary.toml"
            for k, v in self._toml(p).items():
                self._put(self.glossary, "term", k, v, p, local)

    # repository files -------------------------------------------------
    def files(self) -> list[str]:
        if self._files is None:
            out = run_git(self.root, "ls-files", "-z")
            self._files = sorted(f for f in out.split("\0") if f and (self.root / f).is_file())
        return self._files

    def read(self, f: str) -> str | None:
        if f not in self._text:
            p = self.root / f
            try:
                if p.stat().st_size > self.cfg["max_scan_bytes"]:
                    self._text[f] = None
                else:
                    b = p.read_bytes()
                    self._text[f] = None if b"\0" in b[:8192] else b.decode("utf-8", errors="replace")
            except OSError:
                self._text[f] = None
        return self._text[f]

    def is_test(self, f: str) -> bool:
        return any_match(self.cfg["test_globs"], f)

    def prefixes(self) -> dict[str, str]:
        return {str(a.get("prefix", "")): k for k, a in self.areas.items() if a.get("prefix")}

    def tags(self) -> list[Tag]:
        if self._tags is None:
            kw = re.compile(self.cfg["tag_keyword"])
            known = self.prefixes()
            idre = re.compile(r"\b([A-Z][A-Z0-9]*)-(\d+)\b")
            out: list[Tag] = []
            for f in self.files():
                if any_match(self.cfg["ignore"], f):
                    continue
                text = self.read(f)
                if not text or not kw.search(text):
                    continue
                test = self.is_test(f)
                for n, line in enumerate(text.splitlines(), 1):
                    m = kw.search(line)
                    if not m:
                        continue
                    for pre, num in idre.findall(line[m.end():]):
                        if pre in known:
                            out.append(Tag(f, n, f"{pre}-{num}", test))
            self._tags = out
        return self._tags

    def symbol_exists(self, f: str, sym: str) -> bool:
        text = self.read(f)
        if text is None:
            return False
        parts = [p for p in sym.split(".") if p]
        if f.endswith(".py"):
            try:
                tree = ast.parse(text)
            except SyntaxError:
                return False
            names: set[str] = set()
            for n in ast.walk(tree):
                if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    names.add(n.name)
                elif isinstance(n, ast.Assign):
                    names |= {t.id for t in n.targets if isinstance(t, ast.Name)}
                elif isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name):
                    names.add(n.target.id)
            return all(p in names for p in parts)
        return all(re.search(rf"\b{re.escape(p)}\b", text) for p in parts)

    def path_exists(self, entry: str) -> str | None:
        """None when the entry names something real, else why not."""
        base, _, sym = entry.partition("::")
        base = base.strip().removeprefix("./")
        if GLOB_CHARS & set(base):
            return None if any(path_matches(base, f) for f in self.files()) else "matches no tracked file"
        b = base.rstrip("/")
        if b in self.files():
            if sym and not self.symbol_exists(b, sym):
                return f"has no symbol {sym}"
            return None
        if any(f.startswith(b + "/") for f in self.files()):
            return "names a folder; symbols need a file" if sym else None
        return "is not a tracked file or folder"

    # queries ----------------------------------------------------------
    def all_ids(self) -> dict[str, str]:
        out = {}
        for kind, store in (("decision", self.decisions), ("task", self.tasks), ("live", self.live)):
            for k in store:
                out[k] = kind
        return out

    def areas_of(self, f: str) -> list[str]:
        return [k for k, a in self.areas.items() if any_match(list(a.get("paths", [])), f)]

    def governing(self, f: str, active_only: bool = True) -> list[str]:
        ids = {k for k, d in self.decisions.items() if any_match(list(d.get("paths", [])), f)}
        ids |= {t.id for t in self.tags() if t.file == f and not t.test}
        ids &= set(self.decisions)
        if active_only:
            ids = {i for i in ids if self.decisions[i].get("status") == "active"}
        return sorted(ids, key=id_key)

    def tests_for(self, ident: str) -> list[Tag]:
        return [t for t in self.tags() if t.id == ident and t.test]

    def sites_for(self, ident: str) -> list[Tag]:
        return [t for t in self.tags() if t.id == ident and not t.test]

    def importers(self, f: str) -> list[str]:
        if not f.endswith(".py"):
            return []
        mod = f[:-3].replace("/", ".")
        if mod.endswith(".__init__"):
            mod = mod[: -len(".__init__")]
        short = mod.split(".", 1)[1] if mod.startswith("src.") else mod
        out = []
        for g in self.files():
            if not g.endswith(".py") or g == f:
                continue
            text = self.read(g)
            if not text or short.rsplit(".", 1)[-1] not in text:
                continue
            try:
                tree = ast.parse(text)
            except SyntaxError:
                continue
            for n in ast.walk(tree):
                names = []
                if isinstance(n, ast.Import):
                    names = [a.name for a in n.names]
                elif isinstance(n, ast.ImportFrom) and n.module and n.level == 0:
                    names = [n.module] + [f"{n.module}.{a.name}" for a in n.names]
                if any(x == short or x.startswith(short + ".") for x in names):
                    out.append(g)
                    break
        return out

    # the check --------------------------------------------------------
    def check(self) -> list[str]:
        e = list(self.errors)
        lim = self.cfg["limits"]
        tp, lp = self.cfg["task_prefix"], self.cfg["live_prefix"]
        roles_owner, roles_agent = set(self.cfg["owner_roles"]), set(self.cfg["agent_roles"])

        def fields(kind: str, ident: str, rec: dict):
            where = f"{rec['_src']}: {ident}"
            spec = SPEC[kind]
            for k in rec:
                if k.startswith("_"):
                    continue
                if k not in spec:
                    e.append(f"{where}: unknown field `{k}` (allowed: {', '.join(spec)}). A change in substance is a "
                             f"new record, never an extra note field")
            for k, (typ, req) in spec.items():
                v = rec.get(k)
                if v is None or v == "" or v == []:
                    if req:
                        e.append(f"{where}: `{k}` is required")
                    continue
                if typ == S and not isinstance(v, (str, int)):
                    e.append(f"{where}: `{k}` must be text")
                elif typ == L and not (isinstance(v, list) and all(isinstance(x, str) for x in v)):
                    e.append(f"{where}: `{k}` must be a list of text")
                elif typ == D:
                    if not isinstance(v, dt.date) and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(v)):
                        e.append(f"{where}: `{k}` must be a date like 2026-11-02")
                if typ == S and k in lim and len(str(v)) > lim[k]:
                    e.append(f"{where}: `{k}` is {len(str(v))} characters, the limit is {lim[k]}. Keep one current "
                             f"statement; history lives in git")
                if typ == L:
                    for x in v if isinstance(v, list) else []:
                        if len(str(x)) > lim["list_item"]:
                            e.append(f"{where}: an item in `{k}` is over {lim['list_item']} characters")
                allowed = ENUMS.get((kind, k))
                if allowed and v not in allowed:
                    e.append(f"{where}: `{k}` = {v!r}; allowed: {', '.join(sorted(allowed))}")

        # areas
        seen_prefix: dict[str, str] = {}
        for k, a in self.areas.items():
            fields("area", k, a)
            if not re.fullmatch(r"[a-z][a-z0-9-]*", k):
                e.append(f"{a['_src']}: area id `{k}` must be lowercase letters, digits and dashes")
            pre = str(a.get("prefix", ""))
            if pre and not re.fullmatch(r"[A-Z][A-Z0-9]*", pre):
                e.append(f"{a['_src']}: area {k}: prefix `{pre}` must be capitals and digits")
            if pre in (tp, lp):
                e.append(f"{a['_src']}: area {k}: prefix `{pre}` is reserved for tasks or live checks")
            if pre in seen_prefix:
                e.append(f"{a['_src']}: area {k}: prefix `{pre}` is also used by area {seen_prefix[pre]}")
            seen_prefix[pre] = k
            for p in a.get("paths", []) if isinstance(a.get("paths"), list) else []:
                why = self.path_exists(p)
                if why:
                    e.append(f"{a['_src']}: area {k}: path `{p}` {why}")

        ids = self.all_ids()
        # decisions
        for k, d in self.decisions.items():
            where = f"{d['_src']}: {k}"
            fields("decision", k, d)
            area = d["_area"]
            if area not in self.areas:
                e.append(f"{where}: file kb/decisions/{area}.toml names no area in kb/areas.toml")
            else:
                pre = self.areas[area].get("prefix")
                if not re.fullmatch(rf"{re.escape(str(pre))}-\d+", k):
                    e.append(f"{where}: decisions of area {area} are named {pre}-<number>")
            by = d.get("by")
            if by and by not in roles_owner | roles_agent:
                e.append(f"{where}: `by` = {by!r}; allowed: {', '.join(sorted(roles_owner | roles_agent))}")
            if by in roles_owner and not d.get("words") and not d.get("words_source"):
                e.append(f"{where}: an owner decision needs `words` (verbatim) or `words_source` saying why there is "
                         f"no verbatim quote")
            st, sb = d.get("status"), d.get("superseded_by", "")
            if (st == "superseded") != bool(sb):
                e.append(f"{where}: status `superseded` and `superseded_by` go together")
            if sb:
                if sb not in self.decisions:
                    e.append(f"{where}: superseded_by {sb} does not exist")
                elif k not in self.decisions[sb].get("supersedes", []):
                    e.append(f"{where}: {sb} must list {k} in its `supersedes`")
            for s in d.get("supersedes", []) or []:
                if s not in self.decisions:
                    e.append(f"{where}: supersedes {s}, which does not exist")
                elif self.decisions[s].get("superseded_by") != k:
                    e.append(f"{where}: supersedes {s}; set {s}'s status = superseded and superseded_by = {k}")
            for x in d.get("live", []) or []:
                if x not in self.live:
                    e.append(f"{where}: live check {x} does not exist")
            for p in d.get("paths", []) or []:
                why = self.path_exists(p)
                if why:
                    e.append(f"{where}: path `{p}` {why}")
            if self.cfg["coverage"] and st == "active":
                if not (self.tests_for(k) or d.get("live") or d.get("untestable")):
                    e.append(f"{where}: no test carries `decision: {k}`, no `live` check and no `untestable` reason")

        # tasks
        for k, t in self.tasks.items():
            where = f"{t['_src']}: {k}"
            fields("task", k, t)
            if not re.fullmatch(rf"{re.escape(tp)}-\d+", k):
                e.append(f"{where}: tasks are named {tp}-<number>")
            if t.get("area") and t["area"] not in self.areas:
                e.append(f"{where}: area {t['area']} does not exist")
            if t.get("kind") == "question" and not t.get("ask"):
                e.append(f"{where}: a question task needs `ask` (the exact question for the owner)")
            for x in t.get("decisions", []) or []:
                if x not in self.decisions:
                    e.append(f"{where}: decision {x} does not exist")
            for x in t.get("after", []) or []:
                if x not in self.tasks:
                    e.append(f"{where}: after {x}, which does not exist. If {x} is finished, remove it from `after`")
        e += self._cycles()

        # live checks
        for k, v in self.live.items():
            where = f"{v['_src']}: {k}"
            fields("live", k, v)
            if not re.fullmatch(rf"{re.escape(lp)}-\d+", k):
                e.append(f"{where}: live checks are named {lp}-<number>")
            if v.get("area") and v["area"] not in self.areas:
                e.append(f"{where}: area {v['area']} does not exist")
            for x in v.get("decisions", []) or []:
                if x not in self.decisions:
                    e.append(f"{where}: decision {x} does not exist")

        for k, g in self.glossary.items():
            fields("term", k, g)
            for x in g.get("see", []) or []:
                if x not in ids:
                    e.append(f"{g['_src']}: term {k!r}: see {x}, which does not exist")

        # tags in code and tests
        for t in self.tags():
            d = self.decisions.get(t.id)
            if d is None:
                e.append(f"{t.file}:{t.line}: cites decision {t.id}, which does not exist")
            elif d.get("status") != "active":
                now = f" (now {d.get('superseded_by')})" if d.get("superseded_by") else ""
                e.append(f"{t.file}:{t.line}: cites {t.id}, which is {d.get('status')}{now}")

        # every source file in exactly one area
        if self.cfg["ownership"] and self.areas:
            none, many = [], []
            for f in self.files():
                if any_match(self.cfg["ignore"] + self.cfg["ownership_ignore"], f):
                    continue
                n = len(self.areas_of(f))
                if n == 0:
                    none.append(f)
                elif n > 1:
                    many.append(f"{f} ({', '.join(self.areas_of(f))})")
            for label, lst in (("belongs to no area", none), ("belongs to several areas", many)):
                for f in lst[:25]:
                    e.append(f"{f}: {label} (kb/areas.toml)")
                if len(lst) > 25:
                    e.append(f"... and {len(lst) - 25} more files that {label}")

        e += self._lock_problems()
        e += self._generated_problems()
        return e

    def _cycles(self) -> list[str]:
        state: dict[str, int] = {}
        out: list[str] = []

        def visit(k: str, path: list[str]):
            if state.get(k) == 1:
                out.append(f"kb/tasks.toml: `after` loop: {' -> '.join(path + [k])}")
                return
            if state.get(k) == 2 or k not in self.tasks:
                return
            state[k] = 1
            for x in self.tasks[k].get("after", []) or []:
                visit(x, path + [k])
            state[k] = 2

        for k in self.tasks:
            visit(k, [])
        return out

    # the owner-words tripwire ------------------------------------------
    def lock_path(self) -> Path:
        return self.dir / "owner-words.lock"

    def owner_hashes(self) -> dict[str, str]:
        out = {}
        for k, d in self.decisions.items():
            if d.get("by") in self.cfg["owner_roles"] and not d["_local"]:
                raw = f"{as_text(d.get('words'))}\n{as_text(d.get('rule'))}"
                out[k] = hashlib.sha256(raw.encode()).hexdigest()[:16]
        return out

    def read_lock(self) -> dict[str, str]:
        p = self.lock_path()
        out = {}
        if p.exists():
            for line in p.read_text().splitlines():
                line = line.strip()
                if line and not line.startswith("#"):
                    k, _, h = line.partition(" ")
                    out[k] = h.strip()
        return out

    def _lock_problems(self) -> list[str]:
        have, want = self.read_lock(), self.owner_hashes()
        out = []
        for k, h in want.items():
            if k not in have:
                out.append(f"kb/owner-words.lock: owner decision {k} is not locked yet (run `kb lock` and commit it)")
            elif have[k] != h:
                out.append(f"kb/owner-words.lock: the words or rule of owner decision {k} changed. Owner decisions "
                           f"are never reworded: supersede {k} with a new ID. If the owner asked for this exact "
                           f"edit, run `kb lock` so the change shows in the diff")
        for k in have:
            if k not in want:
                out.append(f"kb/owner-words.lock: owner decision {k} disappeared. Owner decisions are superseded or "
                           f"declined, never deleted (run `kb lock` only if the owner asked to delete it)")
        return out

    def write_lock(self) -> tuple[list[str], list[str]]:
        have, want = self.read_lock(), self.owner_hashes()
        changed = sorted((k for k in want if k in have and have[k] != want[k]), key=id_key)
        removed = sorted((k for k in have if k not in want), key=id_key)
        lines = ["# Hashes of each owner decision's words and rule (kb.py lock). A change here is a reworded or",
                 "# deleted owner decision: check that the owner asked for it."]
        lines += [f"{k} {want[k]}" for k in sorted(want, key=id_key)]
        self.lock_path().write_text("\n".join(lines) + "\n")
        return changed, removed

    # generated files ----------------------------------------------------
    def _generated_problems(self) -> list[str]:
        out = []
        has_content = any((self.areas, self.decisions, self.tasks, self.live, self.glossary))
        mp = self.root / self.cfg["map_path"]
        if has_content or mp.exists():
            if not mp.exists() or mp.read_text() != self.gen_map():
                out.append(f"{self.cfg['map_path']} is stale or missing: run `tools/kb/run kb gen`")
        if self.cfg["claude_rules"]:
            want = self.gen_rules()
            rdir = self.root / self.cfg["claude_rules_dir"]
            for name, text in want.items():
                p = rdir / name
                if not p.exists() or p.read_text() != text:
                    out.append(f"{self.rel(p)} is stale or missing: run `tools/kb/run kb gen`")
            for p in rdir.glob("kb-*.md") if rdir.is_dir() else []:
                if p.name not in want:
                    out.append(f"{self.rel(p)} is left over from a removed area: run `tools/kb/run kb gen`")
        return out

    def counts(self, area: str) -> tuple[int, int, int]:
        dec = sum(1 for d in self.decisions.values() if d["_area"] == area and d.get("status") == "active")
        tasks = sum(1 for t in self.tasks.values() if t.get("area") == area)
        live = sum(1 for v in self.live.values() if v.get("area") == area and is_pending(v))
        return dec, tasks, live

    def gen_map(self) -> str:
        """Only tracked records go into the map; the local overlay never reaches a committed file."""
        L_ = [f"# Knowledge map", "", f"<!-- {GENERATED} -->", "",
              "Before editing a file: `tools/kb/run kb show <file>`. Work: `tools/kb/run kb next`. "
              "One area: `tools/kb/run kb area <id>`. Find anything: `tools/kb/run kb search <words>`.", ""]
        areas = {k: a for k, a in self.areas.items() if not a["_local"]}
        if areas:
            L_ += ["| Area | Title | Paths | Active decisions | Open tasks | Pending live checks |",
                   "|---|---|---|---|---|---|"]
            for k in sorted(areas):
                a = areas[k]
                dec, t, lv = self.counts(k)
                paths = ", ".join(f"`{p}`" for p in a.get("paths", []))
                L_.append(f"| {k} | {a.get('title', '')} | {paths} | {dec} | {t} | {lv} |")
            L_.append("")
        qs = [(k, t) for k, t in self.tasks.items() if t.get("kind") == "question" and not t["_local"]]
        if qs:
            L_ += ["## Waiting on the owner", ""]
            L_ += [f"- {k} ({t.get('area', '')}): {t.get('ask', '')}" for k, t in sorted(qs, key=lambda x: id_key(x[0]))]
            L_.append("")
        terms = sorted(k for k, g in self.glossary.items() if not g["_local"])
        if terms:
            L_ += ["## Terms", "", ", ".join(terms) + " (`tools/kb/run kb search <term>`)", ""]
        return "\n".join(L_)

    def gen_rules(self) -> dict[str, str]:
        out = {}
        for k, a in sorted(self.areas.items()):
            if a["_local"]:
                continue
            decs = [(i, d) for i, d in self.decisions.items()
                    if d["_area"] == k and d.get("status") == "active" and not d["_local"]]
            globs = []
            for p in a.get("paths", []):
                p = p.split("::", 1)[0]
                globs.append(p if GLOB_CHARS & set(p) or "." in Path(p).name else p.rstrip("/") + "/**")
            body = ["---", "paths:"] + [f'  - "{g}"' for g in globs] + ["---", f"<!-- {GENERATED} -->", "",
                    f"# {a.get('title', k)} (area `{k}`)", "", a.get("purpose", ""), "",
                    f"Active decisions here. Run `tools/kb/run kb show <file>` for the ones governing one file, their "
                    f"tests and open work; never reword an owner decision (supersede it).", ""]
            for i, d in sorted(decs, key=lambda x: id_key(x[0])):
                body.append(f"- **{i}** ({d.get('by')}): {d.get('rule', '')}")
            text = "\n".join(body).rstrip("\n") + "\n"
            if len(text) > 38000:
                text = text[:37000] + "\n\n(truncated: run `tools/kb/run kb area " + k + "`)\n"
            out[f"kb-{k}.md"] = text
        return out

    def write_generated(self) -> list[str]:
        written = []
        mp = self.root / self.cfg["map_path"]
        mp.parent.mkdir(parents=True, exist_ok=True)
        text = self.gen_map()
        if not mp.exists() or mp.read_text() != text:
            mp.write_text(text); written.append(self.rel(mp))
        if self.cfg["claude_rules"]:
            rdir = self.root / self.cfg["claude_rules_dir"]
            rdir.mkdir(parents=True, exist_ok=True)
            want = self.gen_rules()
            for name, t in want.items():
                p = rdir / name
                if not p.exists() or p.read_text() != t:
                    p.write_text(t); written.append(self.rel(p))
            for p in rdir.glob("kb-*.md"):
                if p.name not in want:
                    p.unlink(); written.append(f"removed {self.rel(p)}")
        return written

    def data(self) -> dict:
        def clean(store):
            return {k: {f: as_text(v) if not isinstance(v, list) else v for f, v in r.items()
                        if not f.startswith("_") or f in ("_area", "_local")} for k, r in store.items()}
        tests = {}
        for t in self.tags():
            tests.setdefault(t.id, []).append({"file": t.file, "line": t.line, "test": t.test})
        return {"areas": clean(self.areas), "decisions": clean(self.decisions), "tasks": clean(self.tasks),
                "live": clean(self.live), "glossary": clean(self.glossary), "tags": tests}


def id_key(i: str):
    m = re.match(r"(.*?)-(\d+)$", i)
    return (m.group(1), int(m.group(2))) if m else (i, 0)


def is_pending(v: dict) -> bool:
    r = as_text(v.get("result")).lower()
    return not v.get("waiver") and not r.startswith("passed")


