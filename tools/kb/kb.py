def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="kb", description="The repository's knowledge registry (repo-kb).")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check", help="validate kb/ and its links to the code")
    p = sub.add_parser("show", help="a file, an ID or an area, with everything linked to it"); p.add_argument("target")
    p = sub.add_parser("area", help="one area's whole slice"); p.add_argument("area")
    sub.add_parser("next", help="ready tasks (questions for the owner first)")
    p = sub.add_parser("live", help="live checks"); p.add_argument("--pending", action="store_true"); p.add_argument("--sitting")
    p = sub.add_parser("search", help="search all records"); p.add_argument("words", nargs="+")
    p = sub.add_parser("gen", help="regenerate kb/MAP.md (and rule files if enabled)"); p.add_argument("--html", action="store_true")
    sub.add_parser("lock", help="refresh kb/owner-words.lock (shows reworded or deleted owner decisions)")
    p = sub.add_parser("new", help="print the next free ID"); p.add_argument("kind", choices=["decision", "task", "live"]); p.add_argument("area", nargs="?")
    p = sub.add_parser("log", help="git history of an ID"); p.add_argument("id")
    p = sub.add_parser("audit", help="print a review packet for one area"); p.add_argument("area")
    p = sub.add_parser("reconcile", help="move an old document in without losing anything")
    p.add_argument("action", choices=["init", "check", "status", "approve", "remove"]); p.add_argument("source", nargs="?")
    p.add_argument("--by", default="")
    sub.add_parser("setup-status", help="are the setup questions answered (kb/setup.toml)?")
    sub.add_parser("version")
    a = ap.parse_args(argv)
    kb = KB(find_root())

    if a.cmd == "check":
        errs = kb.check()
        for x in errs:
            print(f"kb: {x}", file=sys.stderr)
        if errs:
            print(f"kb check: {len(errs)} problem(s)", file=sys.stderr)
            return 1
        print(f"kb check: ok ({len(kb.areas)} areas, {len(kb.decisions)} decisions, {len(kb.tasks)} tasks, "
              f"{len(kb.live)} live checks, {len(kb.glossary)} terms)")
    elif a.cmd == "show":
        cmd_show(kb, a.target)
    elif a.cmd == "area":
        cmd_area(kb, a.area)
    elif a.cmd == "next":
        cmd_next(kb)
    elif a.cmd == "live":
        cmd_live(kb, a.pending, a.sitting)
    elif a.cmd == "search":
        cmd_search(kb, a.words)
    elif a.cmd == "gen":
        for w in kb.write_generated():
            print(f"wrote {w}")
        if a.html:
            print(f"wrote {kb.rel(write_html(kb))} (local only; open it in a browser)")
    elif a.cmd == "lock":
        changed, removed = kb.write_lock()
        for k in changed:
            print(f"lock: owner decision {k} was REWORDED; confirm the owner asked for it")
        for k in removed:
            print(f"lock: owner decision {k} was DELETED; confirm the owner asked for it")
        print("wrote kb/owner-words.lock")
    elif a.cmd == "new":
        if a.kind == "decision":
            if a.area not in kb.areas:
                sys.exit(f"kb.py: name an area: {', '.join(sorted(kb.areas))}")
            pre = kb.areas[a.area]["prefix"]
            nums = [id_key(i)[1] for i, d in kb.decisions.items() if d["_area"] == a.area]
        else:
            pre = kb.cfg["task_prefix"] if a.kind == "task" else kb.cfg["live_prefix"]
            nums = [id_key(i)[1] for i in (kb.tasks if a.kind == "task" else kb.live)]
            nums += [int(m) for m in re.findall(rf"\b{re.escape(pre)}-(\d+)\b",
                                                run_git(kb.root, "log", "--format=%B", check=False))]
        print(f"{pre}-{max(nums, default=0) + 1}")
    elif a.cmd == "log":
        for line in git_log_for(kb, a.id):
            print(line)
    elif a.cmd == "audit":
        cmd_audit(kb, a.area)
    elif a.cmd == "reconcile":
        return cmd_reconcile(kb, a.action, a.source, a.by)
    elif a.cmd == "setup-status":
        errs = setup_problems(kb)
        for x in errs:
            print(f"kb: {x}", file=sys.stderr)
        if errs:
            return 1
        print("setup: all questions answered")
    elif a.cmd == "version":
        print(VERSION)
    return 0


def cmd_reconcile(kb: KB, action: str, src: str | None, by: str) -> int:
    if action == "status":
        rdir = kb.root / kb.cfg["reconcile_dir"]
        for rp in sorted(rdir.glob("*.toml")) if rdir.is_dir() else []:
            doc = kb._toml(rp)
            s = doc.get("source", "?")
            probs = reconcile_problems(kb, s) if (kb.root / s).exists() else ["(source already removed)"]
            state = "approved by " + doc["approved_by"] if doc.get("approved_by") else "not approved"
            print(f"{s}: {'complete' if not probs else f'{len(probs)} open'}; {state}")
        return 0
    if not src:
        sys.exit("kb.py: name the source document")
    src = src.removeprefix("./")
    if action == "init":
        print(f"wrote {kb.rel(reconcile_init(kb, src))}")
        return 0
    probs = reconcile_problems(kb, src)
    if action == "check":
        for x in probs:
            print(f"reconcile: {x}", file=sys.stderr)
        if probs:
            print(f"reconcile {src}: {len(probs)} open", file=sys.stderr)
            return 1
        print(f"reconcile {src}: every block is accounted for")
        return 0
    rp = reconcile_path(kb, src)
    if action == "approve":
        if not by:
            sys.exit("kb.py: --by NAME: who approved it (the owner, after reviewing the file)")
        if probs:
            sys.exit(f"kb.py: {src} is not fully reconciled yet ({len(probs)} open); run `kb reconcile check {src}`")
        text = rp.read_text()
        text = re.sub(r'(?m)^approved_by = ".*"$', f'approved_by = "{by}"', text, count=1)
        text = re.sub(r'(?m)^approved_on = ".*"$', f'approved_on = "{dt.date.today().isoformat()}"', text, count=1)
        rp.write_text(text)
        print(f"{kb.rel(rp)}: approved by {by}")
        return 0
    if action == "remove":
        policy = setup_answer(kb, "docs")
        if policy not in ("delete-after-review", "archive"):
            sys.exit(f"kb.py: kb/setup.toml answers.docs = {policy or '(unanswered)'}; removing old documents needs "
                     f"`delete-after-review` or `archive`")
        if probs:
            sys.exit(f"kb.py: {src} is not fully reconciled ({len(probs)} open)")
        if not kb._toml(rp).get("approved_by"):
            sys.exit(f"kb.py: {src}: the owner has not approved the reconciliation (kb reconcile approve --by)")
        errs = kb.check()
        if errs:
            for x in errs:
                print(f"kb: {x}", file=sys.stderr)
            sys.exit(f"kb.py: `kb check` has {len(errs)} problem(s); fix them first")
        committed = subprocess.run(["git", "cat-file", "-e", f"HEAD:{src}"], cwd=kb.root).returncode == 0
        unchanged = subprocess.run(["git", "diff", "--quiet", "HEAD", "--", src], cwd=kb.root).returncode == 0
        if not (committed and unchanged):
            sys.exit(f"kb.py: commit {src} as reconciled first, so git history keeps exactly the version that was "
                     f"reviewed")
        if policy == "archive":
            dest = kb.root / kb.cfg["archive_dir"] / src
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes((kb.root / src).read_bytes())
        run_git(kb.root, "rm", "-q", "--", src)
        if policy == "archive" and subprocess.run(["git", "check-ignore", "-q", str(dest)], cwd=kb.root).returncode:
            run_git(kb.root, "add", "--", str(dest))
        print(f"removed {src} (staged; commit it){' and copied it to ' + kb.cfg['archive_dir'] if policy == 'archive' else ''}")
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
