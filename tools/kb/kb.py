def short(d: dict, field_: str = "rule") -> str:
    return re.sub(r"\s+", " ", as_text(d.get(field_) or d.get("title"))).strip()


def print_record(kb: KB, ident: str):
    kind = kb.all_ids()[ident]
    rec = {"decision": kb.decisions, "task": kb.tasks, "live": kb.live}[kind][ident]
    print(f"{ident} ({kind}, {rec['_src']}{', local' if rec['_local'] else ''})")
    for k in SPEC[kind]:
        v = rec.get(k)
        if v not in (None, "", []):
            print(f"  {k}: {', '.join(v) if isinstance(v, list) else as_text(v)}")
    if kind == "decision":
        for label, lst in (("tests", kb.tests_for(ident)), ("enforced at", kb.sites_for(ident))):
            for t in lst:
                print(f"  {label}: {t.file}:{t.line}")
        for k, t in kb.tasks.items():
            if ident in (t.get("decisions") or []):
                print(f"  open task: {k} {t.get('title')}")
        for k, v in kb.live.items():
            if ident in (v.get("decisions") or []):
                print(f"  live: {k} {v.get('title')} [{as_text(v.get('result')) or 'pending'}]")
    if kind == "task":
        blocks = [k for k, t in kb.tasks.items() if ident in (t.get("after") or [])]
        if blocks:
            print(f"  blocks: {', '.join(blocks)}")
    log = git_log_for(kb, ident)
    if log:
        print("  history (git log):")
        for line in log[:20]:
            print(f"    {line}")


def git_log_for(kb: KB, ident: str) -> list[str]:
    out = run_git(kb.root, "log", "--oneline", "--no-color", f"--grep={ident}", check=False)
    rx = re.compile(rf"\b{re.escape(ident)}\b")
    lines = [l for l in out.splitlines() if l]
    full = run_git(kb.root, "log", "--format=%h %s%x00%B%x1e", f"--grep={ident}", check=False)
    keep = set()
    for chunk in full.split("\x1e"):
        head, _, body = chunk.strip().partition("\0")
        if head and rx.search(body):
            keep.add(head.split(" ", 1)[0])
    return [l for l in lines if l.split(" ", 1)[0] in keep]


def cmd_show(kb: KB, target: str):
    if target in kb.all_ids():
        print_record(kb, target)
        return
    if target in kb.areas:
        cmd_area(kb, target)
        return
    p = Path(target)
    rel = kb.rel(p.resolve()) if p.exists() else target.removeprefix("./")
    areas = kb.areas_of(rel)
    print(f"{rel}")
    print(f"  area: {', '.join(areas) or '(none: add it to kb/areas.toml)'}")
    gov = kb.governing(rel)
    if gov:
        print("  decisions governing this file:")
        for i in gov:
            d = kb.decisions[i]
            print(f"    {i} ({d.get('by')}): {short(d)}")
            for t in kb.tests_for(i)[:6]:
                print(f"      test: {t.file}:{t.line}")
            if d.get("live"):
                print(f"      live: {', '.join(d['live'])}")
    for a in areas:
        others = [i for i, d in kb.decisions.items() if d["_area"] == a and d.get("status") == "active"
                  and i not in gov]
        if others:
            print(f"  other active decisions in {a}:")
            for i in sorted(others, key=id_key):
                print(f"    {i}: {kb.decisions[i].get('title')}")
    tasks = [k for k, t in kb.tasks.items() if set(t.get("decisions") or []) & set(gov) or t.get("area") in areas]
    if tasks:
        print("  open work:")
        for k in sorted(tasks, key=id_key):
            t = kb.tasks[k]
            print(f"    {k} [{t.get('kind')}/{t.get('status')}] {t.get('title')}")
    lv = [k for k, v in kb.live.items() if set(v.get("decisions") or []) & set(gov) and is_pending(v)]
    if lv:
        print(f"  pending live checks: {', '.join(sorted(lv, key=id_key))}")
    imp = kb.importers(rel)
    if imp:
        print(f"  imported by ({len(imp)}): {', '.join(imp[:12])}{' ...' if len(imp) > 12 else ''}")


def cmd_area(kb: KB, area: str):
    a = kb.areas.get(area)
    if not a:
        sys.exit(f"kb.py: no area {area!r} (areas: {', '.join(sorted(kb.areas))})")
    print(f"{area}: {a.get('title')}  [prefix {a.get('prefix')}]")
    print(f"  paths: {', '.join(a.get('paths', []))}")
    if a.get("purpose"):
        print(f"  purpose: {a['purpose']}")
    decs = sorted(((i, d) for i, d in kb.decisions.items() if d["_area"] == area), key=lambda x: id_key(x[0]))
    for st in ("active", "superseded", "declined"):
        group = [(i, d) for i, d in decs if d.get("status") == st]
        if group:
            print(f"  {st} decisions:")
            for i, d in group:
                print(f"    {i} ({d.get('by')}, {as_text(d.get('date'))}): {short(d) if st == 'active' else d.get('title')}")
    for label, store in (("tasks", kb.tasks), ("live checks", kb.live)):
        rows = sorted((k for k, v in store.items() if v.get("area") == area), key=id_key)
        if rows:
            print(f"  {label}:")
            for k in rows:
                v = store[k]
                state = f"{v.get('kind')}/{v.get('status')}" if label == "tasks" else (as_text(v.get('result')) or "pending")
                print(f"    {k} [{state}] {v.get('title')}")


def cmd_next(kb: KB):
    ready = [k for k, t in kb.tasks.items() if not t.get("after")]
    order = {"question": 0}
    ready.sort(key=lambda k: (order.get(kb.tasks[k].get("kind"), 1), kb.tasks[k].get("status") != "doing", id_key(k)))
    if not kb.tasks:
        print("no tasks")
    for k in ready:
        t = kb.tasks[k]
        extra = f" -> ASK: {t.get('ask')}" if t.get("kind") == "question" else ""
        print(f"{k} [{t.get('kind')}/{t.get('status')}] ({t.get('area')}) {t.get('title')}{extra}")
    waiting = sorted((k for k, t in kb.tasks.items() if t.get("after")), key=id_key)
    if waiting:
        print("waiting:")
        for k in waiting:
            print(f"  {k} after {', '.join(kb.tasks[k]['after'])}: {kb.tasks[k].get('title')}")


def cmd_live(kb: KB, pending: bool, sitting: str | None):
    for k in sorted(kb.live, key=id_key):
        v = kb.live[k]
        if pending and not is_pending(v):
            continue
        if sitting and as_text(v.get("sitting")) != sitting:
            continue
        print(f"{k} [{as_text(v.get('result')) or ('waived' if v.get('waiver') else 'pending')}] ({v.get('area')}"
              f"{', sitting ' + as_text(v.get('sitting')) if v.get('sitting') else ''}) {v.get('title')}")
        print(f"    surface: {v.get('surface')}\n    request: {v.get('request')}\n    pass: {v.get('pass')}")


def cmd_search(kb: KB, words: list[str]):
    ws = [w.lower() for w in words]
    for store in (kb.decisions, kb.tasks, kb.live, kb.glossary):
        for k, r in sorted(store.items(), key=lambda x: id_key(x[0])):
            blob = (k + " " + " ".join(as_text(v) if not isinstance(v, list) else " ".join(v)
                                       for f, v in r.items() if not f.startswith("_"))).lower()
            if all(w in blob for w in ws):
                print(f"{k} ({r['_kind']}): {short(r, 'title') if r['_kind'] != 'term' else r.get('meaning')}")


