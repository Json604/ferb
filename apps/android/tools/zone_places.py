#!/usr/bin/env python3
"""Writes ZonePlaces.kt: each time zone's principal place, for the sky when the phone has no location (PHN-420).

Source: the IANA time zone database (public domain), as macOS ships it: /usr/share/zoneinfo/zone.tab for each zone's
coordinates and tzdata.zi's link lines ("L target alias") so old names such as Asia/Calcutta resolve too. Coordinates
are rounded to 0.01 degree: the sky needs a coarse place only.

    python3 -I apps/android/tools/zone_places.py [zoneinfo dir]
"""

import os
import re
import sys

ZI = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "design", "src", "main", "kotlin", "com", "ferb",
                   "design", "sky", "ZonePlaces.kt")


def degrees(text, width):
    sign = -1 if text[0] == "-" else 1
    digits = text[1:]
    d = int(digits[:width])
    m = int(digits[width:width + 2])
    s = int(digits[width + 2:width + 4]) if len(digits) > width + 2 else 0
    return sign * (d + m / 60 + s / 3600)


def main():
    places = {}
    with open(os.path.join(ZI, "zone.tab"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            _, coords, zone = line.split("\t")[:3]
            m = re.match(r"([+-]\d+)([+-]\d+)$", coords)
            lat, lon = m.group(1), m.group(2)
            places[zone.strip()] = (degrees(lat, 2), degrees(lon, 3))
    links = {}
    with open(os.path.join(ZI, "tzdata.zi"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("L "):
                _, target, alias = line.split()
                links[alias] = target
    for alias, target in links.items():
        while target in links and target not in places:
            target = links[target]
        if target in places and alias not in places:
            places[alias] = places[target]
    with open(os.path.join(ZI, "+VERSION"), encoding="utf-8") as f:
        version = f.read().strip()
    entries = ";".join(f"{z}|{lat:.2f}|{lon:.2f}" for z, (lat, lon) in sorted(places.items()))
    chunks = [entries[i:i + 3000] for i in range(0, len(entries), 3000)]
    body = " +\n        ".join('"' + c + '"' for c in chunks)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(f"""// Generated by apps/android/tools/zone_places.py from the IANA tz database {version} (public domain):
// zone.tab's coordinates, with tzdata.zi's links. Do not edit by hand.
package com.ferb.design.sky

internal object ZonePlaces {{
    const val TZDATA = "{version}"

    private const val TABLE: String =
        {body}

    val all: Map<String, Pair<Double, Double>> by lazy {{
        TABLE.split(';').associate {{ entry ->
            val (zone, lat, lon) = entry.split('|')
            zone to (lat.toDouble() to lon.toDouble())
        }}
    }}
}}
""")
    print(f"wrote {os.path.normpath(OUT)}: {len(places)} zones (tzdata {version})")


if __name__ == "__main__":
    main()
