#!/usr/bin/env python3
"""Writes Sources/FerbDesign/Resources/zone-places.json: each time zone's principal place, for the sky when the phone
has no location (kb PHN-420, PHN-459).

The same table as Android's design sky/ZonePlaces.kt, made the same way as apps/android/tools/zone_places.py: the IANA
time zone database (public domain) as macOS ships it, /usr/share/zoneinfo/zone.tab for each zone's coordinates and
tzdata.zi's link lines ("L target alias") so old names such as Asia/Calcutta resolve too, rounded to 0.01 degree.
ZonePlacesTests checks the result against ZonePlaces.kt entry for entry, so the two phones cannot drift.

    python3 -I apps/ios/Packages/FerbDesign/tools/zone_places.py [zoneinfo dir]
"""

import json
import os
import re
import sys

ZI = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Sources", "FerbDesign", "Resources",
                   "zone-places.json")


def degrees(text, width):
    sign = -1 if text[0] == "-" else 1
    digits = text[1:]
    d = int(digits[:width])
    m = int(digits[width:width + 2])
    s = int(digits[width + 2:width + 4]) if len(digits) > width + 2 else 0
    return sign * (d + m / 60 + s / 3600)


def main():
    places = {}
    with open(os.path.join(ZI, "zone.tab"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            _, coords, zone = line.split("\t")[:3]
            m = re.match(r"([+-]\d+)([+-]\d+)$", coords)
            places[zone.strip()] = (degrees(m.group(1), 2), degrees(m.group(2), 3))
    links = {}
    with open(os.path.join(ZI, "tzdata.zi"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("L "):
                _, target, alias = line.split()
                links[alias] = target
    for alias, target in links.items():
        while target in links and target not in places:
            target = links[target]
        if target in places and alias not in places:
            places[alias] = places[target]
    with open(os.path.join(ZI, "+VERSION"), encoding="utf-8") as f:
        version = f.read().strip()
    # The same text Kotlin's table holds ("%.2f"), read back as numbers.
    table = {z: [float(f"{lat:.2f}"), float(f"{lon:.2f}")] for z, (lat, lon) in sorted(places.items())}
    about = ("Generated by apps/ios/Packages/FerbDesign/tools/zone_places.py from the IANA tz database "
             f"{version} (public domain): zone.tab's coordinates, with tzdata.zi's links. Do not edit by hand.")
    rows = ",\n".join(f"  {json.dumps(z)}: {json.dumps(v)}" for z, v in table.items())
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(f'{{\n"about": {json.dumps(about)},\n"tzdata": {json.dumps(version)},\n"places": {{\n{rows}\n}}\n}}\n')
    json.load(open(OUT, encoding="utf-8"))  # the file must read back as JSON
    print(f"wrote {os.path.normpath(OUT)}: {len(table)} zones (tzdata {version})")


if __name__ == "__main__":
    main()
