"""Owns regenerable Markdown views of durable memory. Must not treat retrieved observations as owner authorization or silently cut stored content.

Markdown view of memory: regenerated from SQLite after every change, one file per subject, only the
items active now (with where each came from). Owner-only permissions; no history kept; files for subjects that no
longer have items are removed."""

import os
from pathlib import Path

from ferb.memory.items import Memory, slug

LABEL = {"owner_stated": "you said", "observed": "observed", "inferred": "inferred (you confirmed)",
         "third_party": "from third-party content"}


def export(memory: Memory, folder: Path) -> list[Path]:
    folder.mkdir(parents=True, exist_ok=True)
    os.chmod(folder, 0o700)
    by_subject: dict[str, list[str]] = {}
    for it in memory.items("active"):
        by_subject.setdefault(it.subject, []).append(
            f"- **{it.kind} · {it.key}**: {it.content}  \n  _{LABEL[it.origin]}, since {it.valid_from:%Y-%m-%d}, "
            f"{len(it.source_ids)} source(s), id {it.id}_")
    written = []
    for subject, lines in sorted(by_subject.items()):
        p = folder / f"{slug(subject.replace(':', '-'), 80)}.md"
        tmp = p.with_suffix(".tmp")
        tmp.write_text(f"# {subject}\n\n_Generated by FERB from its database; edits here are not read back._\n\n"
                       + "\n".join(lines) + "\n")
        os.chmod(tmp, 0o600)
        os.replace(tmp, p)
        written.append(p)
    for old in folder.glob("*.md"):
        if old not in written:
            old.unlink()
    return written
